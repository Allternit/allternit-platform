/** search / model: viewBox 0 0 120 72, width = round(size * 1.67). Gizzi slot (2,14) 40x50, drawing nested at (42,-3) 78x78. */
export function GizziScene({ kind, size = 96, still = false, paper, className }: Omit<EmptyArtProps, 'kind'> & { kind: 'search' | 'model' }) {
  useHeadStyle(EMPTY_ART_STYLE_ID, EMPTY_ART_CSS);
  const cfg = GIZZI_SCENE[kind]!;
  const Art = LINE_ART[kind];
  const w = Math.round(size * EMPTY_ART_SCENE_RATIO);
  const ref = usePlayWhenVisible(still);
  return (
    <div ref={ref} className={className ? `ea ${className}` : 'ea'} data-play={still ? '0' : '1'} style={{ width: w, height: size, ...paperStyle(paper) }} aria-hidden="true">
      <svg viewBox="0 0 120 72" width={w} height={size}>
        <foreignObject x="2" y="14" width="40" height="50">
          <div style={{ width: 40, height: 50, display: 'grid', placeItems: 'center' }}>
            <MascotSlot size={36}>
              <GizziMascot size={36} emotion={cfg.emotion} attention={{ state: 'tracking', target: cfg.target }} label="" testId={'empty-art-gizzi-' + kind} />
            </MascotSlot>
          </div>
        </foreignObject>
        <svg x="42" y="-3" width="78" height="78" viewBox="0 0 96 96">
          <Art />
        </svg>
      </svg>
    </div>
  );
}

/** The one art entry point for console empty states. Decorative: always aria-hidden. */
export function EmptyArt({ kind, size = 96, still = false, paper, className }: EmptyArtProps) {
  useHeadStyle(EMPTY_ART_STYLE_ID, EMPTY_ART_CSS);
  const reduced = usePrefersReducedMotion();
  const ref = usePlayWhenVisible(still);
  if (kind === 'connect-scene') {
    return (
      <ConnectScene
        state="asleep"
        width={Math.round(size * EMPTY_ART_SCENE_RATIO)}
        paper={paper ?? CONSOLE_PAPER}
        className={className}
        gizzi={
          <div style={{ width: 36, height: 48, display: 'grid', placeItems: 'center' }}>
            <MascotSlot size={34}>
              <GizziMascot size={34} emotion="steady" label="" testId="connect-scene-gizzi" />
            </MascotSlot>
          </div>
        }
      />
    );
  }
  if (kind === 'gizzi') {
    const walking = !still && !reduced;
    return (
      <div className={className} style={{ width: size, height: size, display: 'grid', placeItems: 'center' }} aria-hidden="true">
        <MascotSlot size={Math.round(size * 0.75)}>
          <GizziMascot size={Math.round(size * 0.75)} emotion="curious" locomotion={walking ? { style: 'code', phase: 'walk-in' } : undefined} label="" testId="empty-art-gizzi" />
        </MascotSlot>
      </div>
    );
  }
  if (kind === 'search' || kind === 'model') return <GizziScene kind={kind} size={size} still={still} paper={paper} className={className} />;
  const Art = LINE_ART[kind];
  return (
    <div ref={ref} className={className ? `ea ${className}` : 'ea'} data-play={still ? '0' : '1'} style={{ width: size, height: size, ...paperStyle(paper) }} aria-hidden="true">
      <svg viewBox={`0 0 ${EMPTY_ART_VIEWBOX} ${EMPTY_ART_VIEWBOX}`} width={size} height={size}>
        <Art />
      </svg>
    </div>
  );
}
