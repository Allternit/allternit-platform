const REDUCED_MOTION_QUERY = '(prefers-reduced-motion: reduce)';
function subscribeReducedMotion(onChange: () => void): () => void {
  if (typeof window === 'undefined' || !window.matchMedia) return () => {};
  const m = window.matchMedia(REDUCED_MOTION_QUERY);
  m.addEventListener('change', onChange);
  return () => m.removeEventListener('change', onChange);
}
function usePrefersReducedMotion(): boolean {
  return useSyncExternalStore(
    subscribeReducedMotion,
    () => typeof window !== 'undefined' && !!window.matchMedia && window.matchMedia(REDUCED_MOTION_QUERY).matches,
    () => false,
  );
}

/**
 * Sets data-play on the art root: 1 only while it is on screen and the tab is visible.
 * Written to the DOM directly so pausing never re-renders; React leaves the attribute alone while `still` is unchanged.
 */
function usePlayWhenVisible(still: boolean) {
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    const el = ref.current;
    if (!el || still) return;
    let onScreen = true;
    const apply = () => {
      el.dataset.play = onScreen && !document.hidden ? '1' : '0';
    };
    const io =
      typeof IntersectionObserver === 'undefined'
        ? null
        : new IntersectionObserver((entries) => {
            const last = entries[entries.length - 1];
            if (last) onScreen = last.isIntersecting;
            apply();
          });
    io?.observe(el);
    document.addEventListener('visibilitychange', apply);
    apply();
    return () => {
      io?.disconnect();
      document.removeEventListener('visibilitychange', apply);
    };
  }, [still]);
  return ref;
}

/** The console has no --arc-background, so the reference's #fff fallback would paint white in dark mode: default to the page background. */
const CONSOLE_PAPER = 'var(--bg-primary)';

function paperStyle(paper: string | undefined): React.CSSProperties {
  return { '--ea-bg': paper ?? CONSOLE_PAPER } as React.CSSProperties;
}

/** Same footprint as the mascot while its chunk loads, so the layout does not jump. */
function MascotSlot({ size, children }: { size: number; children: React.ReactNode }) {
  return <Suspense fallback={<div style={{ width: size, height: size }} />}>{children}</Suspense>;
}

