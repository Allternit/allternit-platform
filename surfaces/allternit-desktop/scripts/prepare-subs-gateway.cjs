#!/usr/bin/env node
/**
 * Build the subscription gateway (services/subscription-gateway) into
 * resources/subs-gateway/, which electron-builder copies into the app as
 * resources/subs-gateway (extraResources in package.json). Desktop runs it
 * on Electron's own Node (subs-gateway-manager.ts) so phone and desktop-app
 * lanes work with no Sessions computer (Eoj, 2026-10-17: "bundle").
 *
 * Layout (outbase = the gateway package, so relative paths still hold):
 *   package.json                 type: module + the gateway's version (main.ts reads ../package.json)
 *   src/main.js                  entry
 *   adapters/<id>/{adapter,aai}.js, fixtures/offline.js
 *                                one entry each; the loaders already prefer .js over .ts
 *   adapters/<id>/…              manifests, selector packs, fixtures, assets copied as-is
 *   chunks/                      code shared by main and the adapters (one copy of
 *                                each module, so instanceof and module state hold)
 *   migrations/                  SQL; the manager sets SUBS_GATEWAY_MIGRATIONS_DIR
 *   node_modules/playwright{,-core}
 *                                kept external: Playwright resolves its own files at
 *                                runtime and drives the installed Google Chrome
 *   bin/ax-bridge                macOS only: the accessibility helper for desktop-app lanes
 *
 * No native Node modules: the gateway uses node:sqlite (src/store/sqlite.ts).
 * The script ends by booting the bundle on a throwaway state dir and waiting
 * for "listening on http".
 */

const { execFileSync, spawn } = require('child_process');
const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');

const desktopDir = path.resolve(__dirname, '..');
const repoRoot = path.resolve(desktopDir, '..', '..');
const gatewayDir = path.join(repoRoot, 'services', 'subscription-gateway');
const outDir = path.join(desktopDir, 'resources', 'subs-gateway');
const EXTERNAL = ['playwright', 'playwright-core', 'electron', 'chromium-bidi'];

function log(message) {
  process.stdout.write(`[prepare-subs-gateway] ${message}\n`);
}

function fail(message) {
  process.stderr.write(`[prepare-subs-gateway] ✗ ${message}\n`);
  process.exit(1);
}

if (!fs.existsSync(path.join(gatewayDir, 'package.json'))) fail(`missing ${gatewayDir}`);

// The gateway is a pnpm workspace package; install its closure if absent.
if (!fs.existsSync(path.join(gatewayDir, 'node_modules', 'express'))) {
  log('Installing subscription-gateway dependencies (pnpm install --filter subscription-gateway...)…');
  execFileSync('pnpm', ['install', '--frozen-lockfile', '--filter', 'subscription-gateway...'], {
    cwd: repoRoot,
    stdio: 'inherit',
    shell: true,
  });
}

let esbuild;
try {
  esbuild = require(require.resolve('esbuild', { paths: [desktopDir] }));
} catch {
  fail('esbuild is not resolvable from surfaces/allternit-desktop — run pnpm install');
}

const adaptersDir = path.join(gatewayDir, 'adapters');
const adapterIds = fs
  .readdirSync(adaptersDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith('_'))
  .map((d) => d.name)
  .sort();

const entryPoints = [path.join(gatewayDir, 'src', 'main.ts')];
for (const id of adapterIds) {
  for (const rel of ['adapter.ts', 'aai.ts', path.join('fixtures', 'offline.ts')]) {
    const f = path.join(adaptersDir, id, rel);
    if (fs.existsSync(f)) entryPoints.push(f);
  }
}

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

log(`Bundling src/main.ts + ${entryPoints.length - 1} adapter entries → ${path.relative(desktopDir, outDir)}`);
const result = esbuild.buildSync({
  entryPoints,
  outbase: gatewayDir,
  outdir: outDir,
  entryNames: '[dir]/[name]',
  chunkNames: 'chunks/[name]-[hash]',
  bundle: true,
  splitting: true,
  platform: 'node',
  format: 'esm',
  // Electron 41 ships Node 24; node:sqlite needs >= 22.13.
  target: 'node22',
  external: EXTERNAL,
  sourcemap: false,
  minify: false,
  metafile: true,
  logLevel: 'warning',
  banner: {
    // CJS dependencies (express et al.) call require() at runtime.
    js:
      '// Generated by surfaces/allternit-desktop/scripts/prepare-subs-gateway.cjs — do not edit.\n' +
      "import { createRequire as __allternitCreateRequire } from 'node:module';\n" +
      'const require = __allternitCreateRequire(import.meta.url);',
  },
});
if (result.errors.length) fail(`esbuild failed: ${result.errors.map((e) => e.text).join('; ')}`);

const gatewayPkg = JSON.parse(fs.readFileSync(path.join(gatewayDir, 'package.json'), 'utf8'));
fs.writeFileSync(
  path.join(outDir, 'package.json'),
  JSON.stringify({ name: 'subscription-gateway-bundle', version: gatewayPkg.version, private: true, type: 'module' }, null, 2) + '\n'
);

// Adapter data files: everything but TypeScript and READMEs.
let copied = 0;
function copyData(from, to) {
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const src = path.join(from, entry.name);
    const dst = path.join(to, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules' || entry.name === '.build') continue;
      copyData(src, dst);
    } else if (!/\.(ts|tsx|md)$/.test(entry.name)) {
      fs.mkdirSync(to, { recursive: true });
      fs.copyFileSync(src, dst);
      copied++;
    }
  }
}
copyData(adaptersDir, path.join(outDir, 'adapters'));
log(`Copied ${copied} adapter data files`);

fs.cpSync(path.join(gatewayDir, 'src', 'store', 'migrations'), path.join(outDir, 'migrations'), { recursive: true });

// Playwright stays a real package: it reads its own files at runtime.
for (const name of ['playwright', 'playwright-core']) {
  let pkgJson;
  try {
    pkgJson = require.resolve(`${name}/package.json`, { paths: [gatewayDir, path.join(gatewayDir, 'node_modules', 'playwright')] });
  } catch {
    fail(`${name} is not installed for the gateway`);
  }
  const from = fs.realpathSync(path.dirname(pkgJson));
  fs.cpSync(from, path.join(outDir, 'node_modules', name), { recursive: true, dereference: true });
}

// macOS: the accessibility helper desktop-app lanes drive ChatGPT/Claude/Kimi with.
if (process.platform === 'darwin') {
  const axDir = path.join(gatewayDir, 'native', 'ax-bridge');
  log('Building native/ax-bridge (swift build -c release)…');
  execFileSync('swift', ['build', '-c', 'release'], { cwd: axDir, stdio: 'inherit' });
  const bin = path.join(axDir, '.build', 'release', 'ax-bridge');
  if (!fs.existsSync(bin)) fail(`swift build did not produce ${bin}`);
  fs.mkdirSync(path.join(outDir, 'bin'), { recursive: true });
  fs.copyFileSync(bin, path.join(outDir, 'bin', 'ax-bridge'));
  fs.chmodSync(path.join(outDir, 'bin', 'ax-bridge'), 0o755);
}

// Smoke boot: the bundle must start and listen on a throwaway state dir.
async function smokeBoot() {
  const state = fs.mkdtempSync(path.join(os.tmpdir(), 'subs-gateway-smoke-'));
  // Boot a copy outside the repo, as the installed app runs it: inside the
  // repo, Node would find any missing package in the workspace node_modules.
  const bundle = path.join(state, 'bundle');
  fs.cpSync(outDir, bundle, { recursive: true });
  const port = 20000 + Math.floor(Math.random() * 20000);
  const child = spawn(process.execPath, [path.join(bundle, 'src', 'main.js')], {
    env: {
      ...process.env,
      SUBS_GATEWAY_STATE_DIR: path.join(state, 'state'),
      SUBS_GATEWAY_KEYCHAIN: 'file',
      SUBS_GATEWAY_TCP: '1',
      SUBS_GATEWAY_TCP_PORT: String(port),
      SUBS_GATEWAY_ADAPTERS_DIR: path.join(bundle, 'adapters'),
      SUBS_GATEWAY_MIGRATIONS_DIR: path.join(bundle, 'migrations'),
      SUBS_GATEWAY_BUNDLE_ROOT: bundle,
      SUBS_GATEWAY_CANARY_SEC: '0',
    },
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  let output = '';
  child.stdout.on('data', (d) => (output += d));
  child.stderr.on('data', (d) => (output += d));
  const ok = await new Promise((resolve) => {
    const timer = setTimeout(() => resolve(false), 60_000);
    const check = setInterval(() => {
      if (/listening on http/.test(output)) {
        clearTimeout(timer);
        clearInterval(check);
        resolve(true);
      }
    }, 200);
    child.on('exit', () => {
      clearTimeout(timer);
      clearInterval(check);
      resolve(/listening on http/.test(output));
    });
  });
  // Windows keeps state.db locked until the gateway has really exited, so
  // wait for it before removing the temp state dir.
  if (child.exitCode === null && child.signalCode === null) {
    await new Promise((resolve) => {
      child.once('exit', resolve);
      child.kill('SIGTERM');
      setTimeout(() => { child.kill('SIGKILL'); resolve(); }, 10_000);
    });
  }
  try {
    fs.rmSync(state, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
  } catch (e) {
    log(`Smoke boot: could not remove ${state} (${e.code}); leaving it`);
  }
  if (!ok) fail(`bundle did not start:\n${output.slice(-4000)}`);
  const loadErrors = output.split('\n').filter((l) => /failed to load|Cannot find module|ERR_MODULE_NOT_FOUND/.test(l));
  if (loadErrors.length) fail(`bundle started but adapters failed to load:\n${loadErrors.slice(0, 20).join('\n')}`);
  log('Smoke boot: listening');
}

smokeBoot().then(() => {
  const main = fs.readFileSync(path.join(outDir, 'src', 'main.js'));
  const hash = crypto.createHash('sha256').update(main).digest('hex');
  log(`✓ resources/subs-gateway ready (src/main.js sha256 ${hash.slice(0, 16)}…)`);
});
