/*
 * "Meet your bots": the catalog, the account calls and the finish run (iOS MeetBotCatalog.swift,
 * MeetYourBotsFinish.swift; web MeetYourBotsCard + team-slots). Nothing is created until
 * "Start the job"; then [MeetFinish.run] makes the real calls and the done step reports each.
 *
 * The catalog is `assets/meet-bot-catalog.json`, the same JSON iOS embeds in
 * MeetBotCatalogData.swift (generated by ios/Scripts/meet-bot-catalog from allternit-ai
 * `src/lib/bots/templates`). `__MODEL__` / `__PROVIDER__` are filled at create time.
 */

internal const val MEET_MAIN_KEY = "main"

internal data class MeetFirstTask(val prompt: String, val expect: String)

internal data class MeetRoutine(
    val id: String, val label: String, val title: String, val cron: String?, val event: String?,
    val prompt: String, val scheduleLabel: String?,
) {
    val isVisible: Boolean get() = cron != null && scheduleLabel != null
}

internal data class MeetBotTemplate(
    val id: String, val name: String, val tagline: String, val category: String, val color: String,
    val look: String?, val welcome: String?, val firstTask: MeetFirstTask, val starterPrompts: List<String>,
    val handoffs: List<String>, val routines: List<MeetRoutine>, val createBody: JsonElement?,
) {
    val visibleRoutines get() = routines.filter { it.isVisible }
    val hiddenRoutines get() = routines.filter { !it.isVisible }
}

internal data class MeetLook(val id: String, val label: String, val field: String, val avatar: JsonElement?)

internal class MeetBotCatalog(val primary: MeetBotTemplate, val templates: List<MeetBotTemplate>, val looks: List<MeetLook>) {
    fun template(id: String): MeetBotTemplate? = if (id == primary.id) primary else templates.firstOrNull { it.id == id }

    val categories: List<String> get() = templates.map { it.category }.distinct()

    /** "Works well with your team": the bots the team hands work to. */
    fun handoffSuggestions(members: List<String>, limit: Int = 4): List<MeetBotTemplate> {
        val out = mutableListOf<MeetBotTemplate>()
        for (id in members) for (to in template(id)?.handoffs.orEmpty()) {
            val t = template(to) ?: continue
            if (t.id !in members && t !in out) out += t
        }
        return out.take(limit)
    }

    companion object {
        @Volatile private var cached: MeetBotCatalog? = null

        fun get(context: Context): MeetBotCatalog = cached ?: synchronized(this) {
            cached ?: load(context).also { cached = it }
        }

        private fun load(context: Context): MeetBotCatalog {
            val text = runCatching { context.assets.open("meet-bot-catalog.json").bufferedReader().use { it.readText() } }.getOrNull()
            val json = text?.let { runCatching { ApiJson.default.parseToJsonElement(it) }.getOrNull() }
            fun tpl(v: JsonElement?): MeetBotTemplate? {
                val id = v["id"].str() ?: return null
                return MeetBotTemplate(
                    id = id, name = v["name"].str() ?: id, tagline = v["tagline"].str() ?: "", category = v["category"].str() ?: "ops",
                    color = v["color"].str() ?: "#141413", look = v["look"].str(), welcome = v["welcome"].str(),
                    firstTask = MeetFirstTask(v["firstTask"]["prompt"].str() ?: "", v["firstTask"]["expect"].str() ?: ""),
                    starterPrompts = v["starterPrompts"].arr().mapNotNull { it.str() },
                    handoffs = v["handoffs"].arr().mapNotNull { it.str() },
                    routines = v["routines"].arr().mapNotNull { r ->
                        val rid = r["id"].str() ?: return@mapNotNull null
                        MeetRoutine(rid, r["label"].str() ?: rid, r["title"].str() ?: rid, r["cron"].str(), r["event"].str(),
                            r["prompt"].str() ?: "", r["scheduleLabel"].str())
                    },
                    createBody = v["createBody"],
                )
            }
            val primary = tpl(json["primary"]) ?: MeetBotTemplate("primary-a", "A://", "", "ops", "#D97757", null, null,
                MeetFirstTask("", ""), emptyList(), emptyList(), emptyList(), null)
            return MeetBotCatalog(
                primary,
                json["templates"].arr().mapNotNull(::tpl),
                json["looks"].arr().mapNotNull { l ->
                    val id = l["id"].str() ?: return@mapNotNull null
                    MeetLook(id, l["label"].str() ?: id, l["field"].str() ?: "#141413", l["avatar"])
                },
            )
        }

        fun categoryLabel(c: String) = when (c) {
            "ops" -> "Ops"; "marketing" -> "Marketing"; "research" -> "Research"; "delivery" -> "Delivery"
            "finance" -> "Finance"; "sales" -> "Sales"; "engineering" -> "Engineering"; "design" -> "Design"
            else -> c.replaceFirstChar { it.uppercase() }
        }

        /** The look's sprite sheet on the web origin (192×208 frames, 8 columns; frame 0 is the idle pose). */
        fun spriteUrl(slug: String) = "https://ai.allternit.com/avatar-packs/gizzi-youtube/$slug-sheet.webp"
    }
}

/** A bot on the account (`GET /api/v1/agents`, bots only). */
internal data class MeetRosterBot(val id: String, val name: String, val profile: JsonObject, val config: JsonObject, val enabledModes: List<String>) {
    val displayName: String get() = profile["displayName"].str()?.takeIf { it.isNotBlank() } ?: name
    val templateId: String? get() = config["templateId"].str()?.takeIf { it.isNotEmpty() }
    val isMain: Boolean get() = profile["chiefOfStaff"].bool() == true || config["botProfile"]["chiefOfStaff"].bool() == true
    fun allowed(surface: String) = surface in enabledModes || "all" in enabledModes
    /** The bot's colour (web avatar colours), for tiles. */
    val color: String? get() = config["avatar"]["colors"]["primary"].str()
    val look: String? get() = config["avatar"]["look"].str()
}

internal enum class MeetEntry { Setup, BotMode }

internal sealed interface MeetMainChoice {
    data object Primary : MeetMainChoice
    data class Look(val id: String, val name: String) : MeetMainChoice
    data class Bot(val id: String) : MeetMainChoice
}

internal enum class MeetItemStatus { Pending, Running, Ok, Skipped, Failed }

internal data class MeetFinishItem(val key: String, val label: String, val status: MeetItemStatus, val detail: String? = null)

internal data class MeetRoutineDraft(
    val id: String, val botKey: String, val title: String, val prompt: String, val cron: String,
    val scheduleLabel: String, val enabled: Boolean, val custom: Boolean = false,
) {
    companion object {
        fun drafts(t: MeetBotTemplate): List<MeetRoutineDraft> = t.visibleRoutines.mapNotNull { r ->
            val cron = r.cron ?: return@mapNotNull null
            val label = r.scheduleLabel ?: return@mapNotNull null
            MeetRoutineDraft("${t.id}:${r.id}", t.id, r.title, r.prompt, cron, label, true)
        }
    }
}

internal data class MeetFinishInput(
    val entry: MeetEntry,
    val members: List<String>,
    val main: MeetMainChoice,
    val primaryName: String? = null,
    val routines: List<MeetRoutineDraft>,
    val job: Pair<String, String>?,
