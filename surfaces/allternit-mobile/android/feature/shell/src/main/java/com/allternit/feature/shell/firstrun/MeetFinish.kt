/** What a run already did, so Retry only redoes what didn't finish. */
internal class MeetFinishState {
    var mainBotId: String? = null
    var mainName = ""
    val botIds = mutableMapOf<String, String>()
    val created = mutableSetOf<String>()
    val routinesDone = mutableSetOf<String>()
    val hiddenDone = mutableSetOf<String>()
    var sessionId: String? = null
    var sent = false

    fun startedThreadBotId(input: MeetFinishInput): String? {
        val job = input.job ?: return null
        if (!sent || sessionId == null) return null
        return if (job.first == MEET_MAIN_KEY) mainBotId else botIds[job.first]
    }
}

private fun JsonElement?.asObject(): JsonObject? = when (this) {
    is JsonObject -> this
    is JsonPrimitive -> str()?.trim()?.takeIf { it.startsWith("{") }?.let { runCatching { ApiJson.default.parseToJsonElement(it) as? JsonObject }.getOrNull() }
    else -> null
}

private fun JsonElement?.asStrings(): List<String>? {
    val items = when (this) {
        is JsonArray -> this
        is JsonPrimitive -> str()?.let { runCatching { ApiJson.default.parseToJsonElement(it) as? JsonArray }.getOrNull() }
        else -> null
    }
    return items?.mapNotNull { it.str() }?.takeIf { it.isNotEmpty() }
}

internal object MeetAgentsApi {
    suspend fun roster(): List<MeetRosterBot> {
        val json = SetupHttp.v1("GET", "agents")
        val rows = if (json is JsonObject) json["agents"].arr() else json.arr()
        return rows.mapNotNull { row ->
            val id = row["id"].str() ?: return@mapNotNull null
            val config = row["config"].asObject() ?: JsonObject(emptyMap())
            val profile = row["bot_profile"].asObject() ?: config["botProfile"].asObject()
            val isBot = profile != null || row["is_bot"].bool() == true || config["isBot"].bool() == true
            if (!isBot) return@mapNotNull null
            MeetRosterBot(id, row["name"].str() ?: id, profile ?: JsonObject(emptyMap()), config, row["enabled_modes"].asStrings() ?: listOf("chat"))
        }
    }

    /** `POST agents`; a 422 retries with the minimal body older runtimes accept. */
    suspend fun create(body: JsonObject): String = try {
        SetupHttp.v1("POST", "agents", body)["agent"]["id"].str() ?: throw SetupError(null, null, "The bot wasn't created.")
    } catch (e: SetupError) {
        if (e.status != 422) throw e
        val keys = listOf("name", "description", "type", "model", "provider", "harness_config", "enabled_modes", "trust_tier", "is_bot", "bot_profile")
        val minimal = buildMap<String, JsonElement> {
            keys.forEach { k -> body[k]?.let { put(k, it) } }
            put("config", buildJsonObject {
                put("isBot", true)
                body["bot_profile"]?.let { put("botProfile", it) }
                body["config"]["avatar"]?.let { put("avatar", it) }
            })
        }
        SetupHttp.v1("POST", "agents", JsonObject(minimal))["agent"]["id"].str() ?: throw SetupError(null, null, "The bot wasn't created.")
    }

    /** `PATCH agents/:id`, falling back to PUT on runtimes without PATCH. */
    suspend fun update(id: String, body: JsonObject) {
        try {
            SetupHttp.v1("PATCH", "agents/$id", body)
        } catch (e: SetupError) {
            if (e.status !in setOf(404, 405, 422)) throw e
            SetupHttp.v1("PUT", "agents/$id", body)
        }
    }
}

internal object MeetMainBot {
    fun find(bots: List<MeetRosterBot>) = bots.firstOrNull { it.isMain }

    private fun withChief(bot: MeetRosterBot, on: Boolean): JsonObject {
        val profile = JsonObject(bot.profile + mapOf("displayName" to JsonPrimitive(bot.displayName), "chiefOfStaff" to JsonPrimitive(on)))
        val config = JsonObject(bot.config + ("botProfile" to profile))
        return JsonObject(mapOf("bot_profile" to profile, "config" to config))
    }

    /** Makes [botId] the one main bot: unmarks the old one, marks it, and lets it work in cowork. */
    suspend fun set(botId: String, bots: List<MeetRosterBot>) {
        for (bot in bots) if (bot.id != botId && bot.isMain) MeetAgentsApi.update(bot.id, withChief(bot, false))
        val target = bots.firstOrNull { it.id == botId } ?: return
        val needsCowork = !target.allowed("cowork")
        if (target.isMain && !needsCowork) return
        var body = withChief(target, true)
        if (needsCowork) {
            val modes = target.enabledModes.ifEmpty { listOf("chat") }.let { if ("cowork" in it) it else it + "cowork" }
            body = JsonObject(body + ("enabled_modes" to JsonArray(modes.map(::JsonPrimitive))))
        }
        MeetAgentsApi.update(botId, body)
        MainBotReachOut.run(botId, target.displayName)
    }

    /** A:// as the main bot: made from the primary template when missing, then named and dressed. */
    suspend fun setUpPrimary(catalog: MeetBotCatalog, models: SelectedModel, name: String?, avatar: JsonElement?, dropLook: Boolean, bots: List<MeetRosterBot>): String {
        val clean = name?.trim()?.takeIf { it.isNotEmpty() }
        var roster = bots
        val botId = bots.firstOrNull { it.templateId == catalog.primary.id }?.id
            ?: MeetTemplateCreate.create(catalog.primary, models, clean, makeMain = false)
        roster = runCatching { MeetAgentsApi.roster() }.getOrDefault(roster)
        roster.firstOrNull { it.id == botId }?.let { dress(it, clean, avatar, dropLook) }
        roster = runCatching { MeetAgentsApi.roster() }.getOrDefault(roster)
        set(botId, roster)
        return botId
    }

    private suspend fun dress(bot: MeetRosterBot, name: String?, avatar: JsonElement?, dropLook: Boolean) {
        var profile = bot.profile
        var config = bot.config
        var changed = false
        if (name != null && name != bot.displayName) {
            profile = JsonObject(profile + ("displayName" to JsonPrimitive(name)))
            config = JsonObject(config + ("botProfile" to profile))
            changed = true
        }
        if (avatar != null) {
            config = JsonObject(config + ("avatar" to avatar))
            changed = true
        } else if (dropLook && config["avatar"]["look"] != null) {
            config = JsonObject(config - "avatar")
            changed = true
        }
        if (changed) MeetAgentsApi.update(bot.id, JsonObject(mapOf("bot_profile" to profile, "config" to config)))
    }
}

/** The composer's picked model, as the template's `model` / `provider` (iOS MeetTemplateCreate.currentModel). */
internal data class SelectedModel(val id: String?) {
    val pair: Pair<String, String>?
        get() {
            val v = id?.trim()?.takeIf { it.isNotEmpty() } ?: return null
            val slash = v.indexOf('/')
            return if (slash <= 0) v to "allternit" else v.substring(slash + 1) to v.substring(0, slash)
        }
}

internal object MeetTemplateCreate {
    suspend fun create(t: MeetBotTemplate, models: SelectedModel, name: String? = null, makeMain: Boolean): String {
        val model = models.pair ?: ("" to "")
        var body = (t.createBody?.let { fill(it, model) } as? JsonObject)
            ?: throw SetupError(null, null, "This bot template can’t be created on this device.")
        if (name != null && name != t.name) body = renamed(body, name, t)
        if (makeMain) {
            val profile = body["bot_profile"] as? JsonObject
            if (profile != null) {
                val p = JsonObject(profile + ("chiefOfStaff" to JsonPrimitive(true)))
                body = JsonObject(body + ("bot_profile" to p))
                (body["config"] as? JsonObject)?.let { body = JsonObject(body + ("config" to JsonObject(it + ("botProfile" to p)))) }
            }
        }
        return MeetAgentsApi.create(body)
    }

    private fun fill(v: JsonElement, model: Pair<String, String>): JsonElement = when (v) {
        is JsonPrimitive -> when (v.str()) { "__MODEL__" -> JsonPrimitive(model.first); "__PROVIDER__" -> JsonPrimitive(model.second); else -> v }
        is JsonArray -> JsonArray(v.map { fill(it, model) })
        is JsonObject -> JsonObject(v.mapValues { fill(it.value, model) })
    }

    private fun renamed(body: JsonObject, name: String, t: MeetBotTemplate): JsonObject {
        val profile0 = body["bot_profile"] as? JsonObject ?: return body
        var profile = JsonObject(profile0 + ("displayName" to JsonPrimitive(name)))
        t.welcome?.takeIf { it.isNotEmpty() }?.let { profile = JsonObject(profile + ("welcomeMessage" to JsonPrimitive(it.replace("{name}", name)))) }
        var out = JsonObject(body + ("bot_profile" to profile))
        (out["config"] as? JsonObject)?.let { out = JsonObject(out + ("config" to JsonObject(it + ("botProfile" to profile)))) }
        val handle = slugify(name)
        return JsonObject(out + ("name" to JsonPrimitive(if (handle.length >= 3) handle else "${handle.ifEmpty { "my" }}-bot")))
    }

    /** iOS BotModeStore.slugify. */
    fun slugify(s: String) = s.lowercase().replace(Regex("[^a-z0-9]+"), "-").trim('-')
}

/** The main bot says hello once it is set, then a morning check-in routine (best effort). */
internal object MainBotReachOut {
    const val CHECK_IN_TITLE = "Morning check-in"
    const val CHECK_IN_CRON = "0 9 * * *"
    const val CHECK_IN_PROMPT = "Morning check-in. Review my open tasks and threads and my Inbox (what needs me). " +
        "Then use suggest_task to offer 1 to 3 concrete pieces of work you could take off my plate today, each with a short reason. " +
        "Don't start any of it until I say go ahead. If nothing is worth offering, say so in one line."

    suspend fun run(botId: String, botName: String) {
        val reply = runCatching { SetupHttp.v1("POST", "bots/$botId/reach-out", JsonObject(emptyMap())) }.getOrNull() ?: return
        if (reply["status"].str() != "posted") return
        runCatching { MeetFinish.installRoutine(botId, botName, CHECK_IN_TITLE, CHECK_IN_PROMPT, CHECK_IN_CRON, null, enabled = true, checkIn = true) }
    }
}

internal object MeetFinish {
    fun plannedItems(input: MeetFinishInput, catalog: MeetBotCatalog): List<MeetFinishItem> {
        val items = mutableListOf(MeetFinishItem("main", "Main bot", MeetItemStatus.Pending))
        input.members.forEach { items += MeetFinishItem("bot:$it", catalog.template(it)?.name ?: it, MeetItemStatus.Pending) }
        val hidden = input.members.any { catalog.template(it)?.hiddenRoutines?.isNotEmpty() == true }
        if (input.routines.isNotEmpty() || hidden) items += MeetFinishItem("routines", "Routines", MeetItemStatus.Pending)
        if (input.job != null) items += MeetFinishItem("thread", "Thread #1", MeetItemStatus.Pending)
        return items
    }

    private fun message(e: Throwable) = (e as? SetupError)?.message?.takeIf { it.isNotBlank() } ?: "Something went wrong. Try again."

    suspend fun run(
        input: MeetFinishInput,
        catalog: MeetBotCatalog,
        models: SelectedModel,
        state: MeetFinishState,
        prior: List<MeetFinishItem>?,
        report: (List<MeetFinishItem>) -> Unit,
    ): List<MeetFinishItem> {
        var items = if (!prior.isNullOrEmpty()) prior else plannedItems(input, catalog)
        fun set(key: String, status: MeetItemStatus, label: String? = null, detail: String? = null) {
            val i = items.indexOfFirst { it.key == key }
            items = if (i >= 0) items.toMutableList().also { it[i] = it[i].copy(status = status, detail = detail, label = label ?: it[i].label) }
            else items + MeetFinishItem(key, label ?: key, status, detail)
            report(items)
        }
        fun todo(key: String): Boolean = items.firstOrNull { it.key == key }?.status.let { it != MeetItemStatus.Ok && it != MeetItemStatus.Skipped }

        var roster = try {
            MeetAgentsApi.roster()
        } catch (e: kotlinx.coroutines.CancellationException) {
            throw e
        } catch (e: Exception) {
            val why = "Couldn’t reach your bots (${message(e)}). Check that your computer is online, then retry."
            items.filter { it.status != MeetItemStatus.Ok && it.status != MeetItemStatus.Skipped }.forEach { set(it.key, MeetItemStatus.Failed, detail = why) }
            return items
        }

        if (todo("main")) {
            set("main", MeetItemStatus.Running)
            try {
                val mainId = when (input.entry) {
                    MeetEntry.BotMode -> MeetMainBot.find(roster)?.id ?: throw SetupError(null, null, "No main bot found. Set one up from the Bots rail, then try again.")
                    MeetEntry.Setup -> when (val m = input.main) {
                        is MeetMainChoice.Bot -> { MeetMainBot.set(m.id, roster); m.id }
                        is MeetMainChoice.Look -> MeetMainBot.setUpPrimary(catalog, models, m.name, catalog.looks.firstOrNull { it.id == m.id }?.avatar, false, roster)
                        MeetMainChoice.Primary -> MeetMainBot.setUpPrimary(catalog, models, input.primaryName, null, true, roster)
                    }
                }
                roster = runCatching { MeetAgentsApi.roster() }.getOrDefault(roster)
                state.mainBotId = mainId
                state.mainName = roster.firstOrNull { it.id == mainId }?.displayName ?: "A://"
                set("main", MeetItemStatus.Ok, "Main bot · ${state.mainName}",
                    if (input.entry == MeetEntry.BotMode) "Already your main bot" else "Pinned to the top of the Bots rail")
            } catch (e: kotlinx.coroutines.CancellationException) {
                throw e
            } catch (e: Exception) {
                set("main", MeetItemStatus.Failed, detail = message(e))
            }
        }

        for (id in input.members) {
            val key = "bot:$id"
            if (!todo(key)) continue
            val t = catalog.template(id)
            if (t == null) { set(key, MeetItemStatus.Failed, detail = "This bot template isn’t in the catalog."); continue }
            set(key, MeetItemStatus.Running)
            val existing = roster.firstOrNull { it.templateId == id }
            if (existing != null) {
                state.botIds[id] = existing.id
                set(key, MeetItemStatus.Skipped, detail = "Already on your account")
                continue
            }
            try {
                val makeMain = roster.none { it.isMain } && state.mainBotId == null
                val botId = MeetTemplateCreate.create(t, models, makeMain = makeMain)
                state.botIds[id] = botId
                state.created += id
                set(key, MeetItemStatus.Ok, detail = "Added to your bots")
            } catch (e: kotlinx.coroutines.CancellationException) {
                throw e
            } catch (e: Exception) {
                set(key, MeetItemStatus.Failed, detail = message(e))
            }
        }
        if (state.created.isNotEmpty()) roster = runCatching { MeetAgentsApi.roster() }.getOrDefault(roster)
        fun botId(key: String) = if (key == MEET_MAIN_KEY) state.mainBotId else state.botIds[key]
        fun name(id: String) = roster.firstOrNull { it.id == id }?.displayName ?: "Bot"

        if (items.any { it.key == "routines" } && todo("routines")) {
            set("routines", MeetItemStatus.Running)
            val problems = mutableListOf<String>()
            var added = 0
            for (r in input.routines) {
                if (r.id in state.routinesDone) { added++; continue }
                val owner = botId(r.botKey)
                if (owner == null) { problems += "${r.title}: its bot isn’t set up"; continue }
                try {
                    installRoutine(owner, name(owner), r.title, r.prompt, r.cron, null, r.enabled)
                    state.routinesDone += r.id
                    added++
                } catch (e: kotlinx.coroutines.CancellationException) {
                    throw e
                } catch (e: Exception) {
                    problems += "${r.title}: ${message(e)}"
                }
            }
            for (id in state.created.sorted()) {
                val t = catalog.template(id) ?: continue
                val owner = state.botIds[id] ?: continue
                for (r in t.hiddenRoutines) {
                    val k = "$id:${r.id}"
                    if (k in state.hiddenDone) continue
                    try {
                        installRoutine(owner, name(owner), r.label, r.prompt, r.cron, r.event, enabled = false)
                        state.hiddenDone += k
                    } catch (e: kotlinx.coroutines.CancellationException) {
                        throw e
                    } catch (e: Exception) {
                        problems += "${r.label}: ${message(e)}"
                    }
                }
            }
            val on = input.routines.count { it.enabled && it.id in state.routinesDone }
            if (problems.isEmpty()) set("routines", MeetItemStatus.Ok, detail = "$on on" + if (added > on) ", ${added - on} paused" else "")
            else set("routines", MeetItemStatus.Failed, detail = "$added added, ${problems.size} didn’t: " +
                problems.take(2).joinToString("; ") + if (problems.size > 2) "…" else "")
        }

        val job = input.job
        if (job != null && items.any { it.key == "thread" } && todo("thread")) {
            set("thread", MeetItemStatus.Running)
            try {
                val owner = botId(job.first) ?: throw SetupError(null, null, "The bot that owns this job isn’t set up.")
                if (state.sessionId == null) state.sessionId = mainChatSessionId(owner)
                val sid = state.sessionId
                if (!state.sent && sid != null) {
                    SetupHttp.v1("POST", "agent-sessions/$sid/messages", buildJsonObject {
                        put("text", job.second.trim())
                        put("metadata", buildJsonObject { put("time_zone", TimeZone.getDefault().id) })
                    })
                    state.sent = true
                }
                set("thread", MeetItemStatus.Ok, "Thread #1 · ${name(owner)}", "Running")
            } catch (e: kotlinx.coroutines.CancellationException) {
                throw e
            } catch (e: Exception) {
                set("thread", MeetItemStatus.Failed, detail = message(e))
            }
        }
        return items
    }

    /**
     * The bot's main chat (iOS BotModeStore.mainChatSessionId): its pinned canonical thread, the
     * newest "Main chat" thread with a session, else a new bot session that greets first.
     */
    suspend fun mainChatSessionId(botId: String): String {
        val agent = SetupHttp.v1("GET", "agents/$botId")["agent"]
        agent["config"].asObject()?.get("canonicalThreadId").str()?.takeIf { it.isNotEmpty() }?.let { return it }
        val threads = runCatching { SetupHttp.v1("GET", "threads", query = mapOf("botId" to botId, "includeResolved" to "true")) }.getOrNull()?.get("threads").arr()
        threads.filter { t ->
            val sid = t["currentSessionId"].str() ?: t["current_session_id"].str()
            val createdBy = t["createdBy"].str() ?: t["created_by"].str()
            t["kind"].str() == "standing" && createdBy == "import" && t["title"].str() == "Main chat" && sid != null && t["incognito"].bool() != true
        }.maxByOrNull { it["lastActivityAt"].str() ?: it["last_activity_at"].str() ?: "" }?.let { t ->
            (t["currentSessionId"].str() ?: t["current_session_id"].str())?.let { return it }
        }
        val profile = agent["bot_profile"].asObject() ?: agent["config"].asObject()?.get("botProfile").asObject()
        val botName = profile["displayName"].str()?.takeIf { it.isNotBlank() } ?: agent["name"].str() ?: "Bot"
        val session = SetupHttp.v1("POST", "agent-sessions", buildJsonObject {
            put("name", "Bot Chat")
            put("origin_surface", "chat")
            put("session_mode", "agent")
            put("agent_id", botId)
            put("agent_name", botName)
            put("metadata", buildJsonObject {
                put("botCanonicalFor", botId); put("isBot", "true"); put("agentId", botId); put("botName", botName)
            })
        })
        val sid = session["id"].str() ?: session["session"]["id"].str() ?: throw SetupError(null, null, "The bot's chat wasn't created.")
        // The bot speaks first. Best effort: a runtime that can't store assistant notes still opens the chat.
        if (sid.startsWith("ses")) {
            val welcome = profile["welcomeMessage"].str()?.trim()?.takeIf { it.isNotEmpty() }
                ?: "Hi, I'm $botName. What can I help you with?"
            runCatching {
                SetupHttp.v1("POST", "agent-sessions/$sid/messages", buildJsonObject {
                    put("text", welcome); put("role", "assistant"); put("noReply", true)
                    put("metadata", buildJsonObject { put("source", "bot-greeting") })
                })
            }
        }
        return sid
    }

    /** One routine for a bot (`POST automation/routines`); a paused one is set paused right after. */
    suspend fun installRoutine(botId: String, botName: String, title: String, prompt: String, cron: String?, event: String?, enabled: Boolean, checkIn: Boolean = false) {
        val row = SetupHttp.v1("POST", "automation/routines", buildJsonObject {
            put("name", "[bot:$botName] $title")
            put("description", prompt)
            put("agent_id", botId)
            put("schedule_type", if (cron == null) "manual" else "cron")
            put("schedule_expression", cron ?: "")
            put("timezone", TimeZone.getDefault().id)
            put("execution_domain", "local")
            put("config", buildJsonObject {
                put("jobType", "agent"); put("prompt", prompt)
                if (cron == null && event != null) put("trigger", event)
            })
            put("metadata", buildJsonObject {
                put("source", "bot-routine"); put("botName", botName); put("title", title); put("fromTemplate", true)
                if (checkIn) put("checkIn", true)
            })
        })
        if (enabled) return
        val id = row["id"].str() ?: row["routine"]["id"].str() ?: return
        try {
            SetupHttp.v1("PUT", "automation/routines/$id", buildJsonObject { put("status", "paused") })
        } catch (e: Exception) {
            runCatching { SetupHttp.v1("DELETE", "automation/routines/$id") }
            throw e
        }
    }
}

/**
 * Whether the person has seen "Meet your bots" (iOS BotsIntroStore): the account flag
 * `botsIntroSeenAt` (`PUT {cloud}/api/v1/me/flags`), with a local copy.
 */
internal object BotsIntro {
    const val FLAG_KEY = "botsIntroSeenAt"
    private const val LOCAL_KEY = "allternit-bots-intro-seen"

    suspend fun markSeen(context: Context) {
        val at = Instant.now().toString()
        context.getSharedPreferences("allternit_shell", Context.MODE_PRIVATE).edit().putString(LOCAL_KEY, at).apply()
        runCatching {
            SetupHttp.send("PUT", ApiConfig().cloudBaseUrl.newBuilder().addPathSegments("api/v1/me/flags").build(),
                buildJsonObject { put(FLAG_KEY, at) })
        }
    }
}
