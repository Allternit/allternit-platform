#!/usr/bin/env node
// Parity ledger: one row per iOS screen and per web phone screen, so no screen is lost
// when the native Android app is built. Node 20+, no dependencies.
//
//   node scripts/parity-ledger.mjs --web <allternit-ai path>   (or env ALLTERNIT_AI_DIR)
//   node scripts/parity-ledger.mjs --web <path> --check        (exit 1 if a screen has no row)
//
// Re-running merges: hand-edited Android path / Status / Proof survive; new screens are
// added as `todo`; vanished screens stay, marked `todo (source removed)`.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const NONE = '—';
const PHONE = 'src/fabric-session/phone';
const SCREENS = `${PHONE}/screens`;
const NAV = `${PHONE}/phone-nav.ts`;
const IOS_SUFFIX = /(View|Screen|Sheet|Page)\.swift$/;
const NA_MESSAGES = 'N/A: no Android equivalent (Eoj 2026-11-18)';

// Web screen -> area, and the iOS file that covers it (HANDOFF step-1 item 6).
const WEB_MAP = {
  [`${SCREENS}/ChatsScreen.tsx`]: { area: 'Chat' },
  [`${SCREENS}/AciScreen.tsx`]: { area: 'ACI' },
  [`${SCREENS}/BotsScreen.tsx`]: { area: 'Bots' },
  [`${SCREENS}/ProjectsScreen.tsx`]: { area: 'Projects' },
  [`${SCREENS}/SettingsScreen.tsx`]: { area: 'Settings' },
  [`${SCREENS}/PhoneCodeSessionsView.tsx`]: { area: 'Code' },
  [`${SCREENS}/PhoneCodeTerminal.tsx`]: { area: 'Code' },
  [`${SCREENS}/LinkedPhoneOverlay.tsx`]: { area: 'Phones', ios: 'ios/Features/Phones/PhoneLiveView.swift' },
  [`${SCREENS}/LinkedPhonesSection.tsx`]: { area: 'Phones' },
  [`${SCREENS}/PhoneComputerViewOverlay.tsx`]: { area: 'ACI', ios: 'ios/Features/ACI/Views/ACIComputerDetailView.swift' },
  [`${SCREENS}/PhoneDesktopOverlay.tsx`]: { area: 'Agents', ios: 'ios/Features/Agents/Desktop/BotDesktopView.swift' },
  [`${SCREENS}/PhoneMiniAppOverlay.tsx`]: { area: 'ACI', ios: 'ios/Features/ACI/Views/MiniAppRuntimeView.swift' },
  [`${SCREENS}/PhoneOverviewOverlay.tsx`]: { area: 'Shell', ios: 'ios/Features/Shell/SessionOverviewView.swift' },
  [`${SCREENS}/PhoneSearchOverlay.tsx`]: { area: 'Shell', ios: 'ios/Features/Shell/ShellSearchView.swift' },
  [`${SCREENS}/PhoneTeachOverlay.tsx`]: { area: 'ACI', ios: 'ios/Features/ACI/Views/TeachView.swift' },
};
const SECTION_AREA = {
  chats: 'Chat', projects: 'Projects', artifacts: 'Artifacts', code: 'Code', tasks: 'Automation',
  automation: 'Automation', meetings: 'Calls', customize: 'Customize', 'model-lab': 'Models',
  bots: 'Bots', aci: 'ACI', settings: 'Settings',
};
const SECTION_IOS = { meetings: 'ios/Features/Calls/Meetings/MeetingsView.swift' };
const MODE_AREA = { home: 'Shell', bots: 'Shell', code: 'Shell', aci: 'Shell' };

const SYSTEM = [
  ['iMessage extension', 'ios/AllternitMessages', NA_MESSAGES],
  ['Focus filter', 'ios/SystemSurfaces/Intents/FocusFilter.swift', NA_MESSAGES],
  ['Widgets -> Glance app widgets', 'ios/AllternitWidgets', 'todo'],
  ['Live Activities -> ongoing notifications', 'ios/AllternitWidgets', 'todo'],
  ['Control widgets -> Quick Settings tiles', 'ios/AllternitWidgets', 'todo'],
  ['Share extension -> Android share target', 'ios/AllternitShare', 'todo'],
  ['File Provider -> existing DocumentsProvider', 'ios/AllternitFileProvider', 'todo'],
  ['App Intents -> app shortcuts', 'ios/SystemSurfaces/Intents', 'todo'],
  ['Push notifications', 'ios/AllternitNotifications', 'todo'],
  ['Screen share (broadcast)', 'ios/AllternitScreen', 'todo'],
];

const HEADER = `# Android parity ledger

Generated by \`scripts/parity-ledger.mjs\`. Do not add or remove rows by hand: re-run the script
(\`node scripts/parity-ledger.mjs --web <allternit-ai path>\`). Re-running keeps what you edited in the
**Android path**, **Status** and **Proof** columns.

| Column | Meaning |
| --- | --- |
| Screen | File or section name |
| iOS path | Swift file under \`ios/Features/**\` (or the system-surface folder) |
| Web path | Phone PWA screen under \`src/fabric-session/phone/\` in allternit-ai; several are joined with \`<br>\` |
| Android path | Kotlin file or module that implements it (hand-edited) |
| Status | \`todo\`, \`built\` (code merged, not yet compared), \`proved\` (paired iOS/Android shots and flow pass), or \`N/A: <reason>\` |
| Proof | Link to the paired screenshots or flow run; required for \`proved\` |

\`todo (source removed)\` means the iOS or web file no longer exists; decide whether the row still applies.
The cutover rule needs 0 \`todo\` and 0 \`built\` rows.
`;

function parseArgs(argv) {
  const o = { check: false, web: process.env.ALLTERNIT_AI_DIR || '', root: '' };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--check') o.check = true;
    else if (argv[i] === '--web') o.web = argv[++i];
    else if (argv[i] === '--root') o.root = argv[++i];
    else { console.error(`unknown argument ${argv[i]}`); process.exit(2); }
  }
  return o;
}

function walk(dir, base = dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, base, out);
    else out.push(p.slice(base.length + 1));
  }
  return out;
}

function git(web, args) {
  return execFileSync('git', ['-C', web, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 64 << 20 });
}

function makeWebReader(web) {
  let useGit = false;
  try { git(web, ['rev-parse', '--verify', 'origin/main']); useGit = true; } catch { /* fall back to working copy */ }
  return {
    list(dir) {
      if (useGit) return git(web, ['ls-tree', '-r', '--name-only', 'origin/main', dir]).split('\n').filter(Boolean);
      const abs = join(web, dir);
      return existsSync(abs) ? walk(abs, web) : [];
    },
    read(path) {
      if (useGit) return git(web, ['show', `origin/main:${path}`]);
      return readFileSync(join(web, path), 'utf8');
    },
  };
}

const base = (p) => p.split('/').pop().replace(/\.(swift|tsx?)$/, '');

function collect(root, web) {
  const iosDir = join(root, 'ios', 'Features');
  const ios = existsSync(iosDir)
    ? walk(iosDir, root).filter((p) => IOS_SUFFIX.test(p)).sort()
    : [];
  const reader = makeWebReader(web);
  const screens = reader.list(SCREENS)
    .filter((p) => /\.tsx?$/.test(p) && !/\.(test|spec)\.tsx?$/.test(p)).sort();
  const nav = reader.read(NAV);
  const values = (name) => {
    const m = nav.match(new RegExp(`export type ${name}\\s*=\\s*([^;]+);`));
    return m ? [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]) : [];
  };
  return { ios, screens, sections: values('PhoneSection'), modes: values('PhoneMode') };
}

// Build the current row set: key -> { table, screen, ios, web, fixedStatus? }
function buildRows(root, web) {
  const { ios, screens, sections, modes } = collect(root, web);
  const iosSet = new Set(ios);
  const rows = new Map();
  for (const p of ios) {
    rows.set(p, { table: p.split('/')[2], screen: base(p), ios: p, web: [] });
  }
  const addWeb = (webPath, screen, area, iosPath) => {
    if (iosPath && rows.has(iosPath)) { rows.get(iosPath).web.push(webPath); return; }
    rows.set(webPath, { table: area || 'Unmatched web', screen, ios: NONE, web: [webPath] });
  };
  for (const p of screens) {
    const m = WEB_MAP[p];
    addWeb(p, base(p), m?.area, m?.ios);
  }
  for (const s of sections) {
    addWeb(`${NAV} (PhoneSection ${s})`, `section: ${s}`, SECTION_AREA[s], SECTION_IOS[s]);
  }
  for (const m of modes) addWeb(`${NAV} (PhoneMode ${m})`, `mode: ${m}`, MODE_AREA[m]);
  for (const [screen, path, status] of SYSTEM) {
    rows.set(`sys:${screen}`, { table: 'System surfaces', screen, ios: path, web: [], system: true, fixedStatus: status });
  }
  return { rows, iosSet };
}

const esc = (s) => String(s).replace(/\|/g, '\\|');
const splitRow = (line) => line.trim().replace(/^\|/, '').replace(/\|$/, '').split(/(?<!\\)\|/).map((c) => c.trim().replace(/\\\|/g, '|'));
const rowKey = (table, c) => (table === 'System surfaces' ? `sys:${c[0]}` : c[1] !== NONE ? c[1] : c[2].split('<br>')[0]);

function parseExisting(text) {
  const out = new Map();
  let table = null;
  for (const line of text.split('\n')) {
    const h = line.match(/^## (.+)$/);
    if (h) { table = h[1].trim(); continue; }
    if (!table || !line.startsWith('|')) continue;
    const c = splitRow(line);
    if (c.length !== 6 || c[0] === 'Screen' || /^-+$/.test(c[0])) continue;
    out.set(rowKey(table, c), { table, screen: c[0], ios: c[1], web: c[2] === NONE ? [] : c[2].split('<br>'), android: c[3], status: c[4], proof: c[5] });
  }
  return out;
}

function render(rows, existing) {
  const merged = new Map();
  for (const [key, r] of rows) {
    const e = existing.get(key);
    let status = e ? e.status : (r.fixedStatus || 'todo');
    if (e && /^todo \(source removed\)/.test(status)) status = 'todo';
    merged.set(key, { ...r, android: e ? e.android : NONE, status, proof: e ? e.proof : NONE });
  }
  for (const [key, e] of existing) {
    if (merged.has(key)) continue;
    const status = /^todo \(source removed\)/.test(e.status) ? e.status : 'todo (source removed)';
    merged.set(key, { ...e, status });
  }
  const tables = new Map();
  for (const r of merged.values()) {
    if (!tables.has(r.table)) tables.set(r.table, []);
    tables.get(r.table).push(r);
  }
  const names = [...tables.keys()].filter((t) => t !== 'Unmatched web' && t !== 'System surfaces').sort();
  for (const t of ['Unmatched web', 'System surfaces']) if (tables.has(t)) names.push(t);
  const counts = {};
  let md = HEADER;
  for (const t of names) {
    md += `\n## ${t}\n\n| Screen | iOS path | Web path | Android path | Status | Proof |\n| --- | --- | --- | --- | --- | --- |\n`;
    for (const r of tables.get(t).sort((a, b) => (a.ios + a.web[0]).localeCompare(b.ios + b.web[0]))) {
      md += `| ${[r.screen, r.ios, r.web.length ? r.web.join('<br>') : NONE, r.android, r.status, r.proof].map(esc).join(' | ')} |\n`;
      const k = r.status.startsWith('N/A') ? 'N/A' : r.status.split(':')[0];
      counts[k] = (counts[k] || 0) + 1;
    }
  }
  return { md, counts, total: merged.size };
}

export function run(argv, log = console.log) {
  const o = parseArgs(argv);
  const root = resolve(o.root || join(dirname(fileURLToPath(import.meta.url)), '..'));
  if (!o.web) { log('error: pass --web <allternit-ai path> or set ALLTERNIT_AI_DIR'); return 2; }
  const ledger = join(root, 'PARITY.md');
  const existing = existsSync(ledger) ? parseExisting(readFileSync(ledger, 'utf8')) : new Map();
  const { rows } = buildRows(root, resolve(o.web));
  if (o.check) {
    const missing = [...rows.keys()].filter((k) => !k.startsWith('sys:') && !existing.has(k));
    if (missing.length) {
      log(`PARITY.md is missing ${missing.length} row(s); run parity-ledger.mjs without --check:`);
      for (const k of missing) log(`  ${k}`);
      return 1;
    }
    log(`parity ledger ok: ${rows.size} source screens/surfaces all have rows`);
    return 0;
  }
  const { md, counts, total } = render(rows, existing);
  writeFileSync(ledger, md);
  log(`PARITY.md: ${total} rows - ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(', ')}`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(run(process.argv.slice(2)));
}
