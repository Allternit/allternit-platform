// ---------------------------------------------------------------- validation

function fail(msg) {
  console.error(`pet-offers contract: ${msg}`);
  process.exit(1);
}

// Constructs that do not work the same in JS RegExp, ICU and java.util.regex.
const NON_PORTABLE = [
  [/\(\?<[=!]/, 'lookbehind'],
  [/\(\?<[A-Za-z]/, 'named group'],
  [/\(\?P/, 'named group'],
  [/\\k</, 'named backreference'],
  [/\\[1-9]/, 'backreference'],
  [/\(\?[imsxU-]+[):]/, 'inline flags'],
  [/\(\?>/, 'atomic group'],
  [/[*+?}][+]/, 'possessive quantifier'],
  [/\\[pP]\{/, 'unicode property'],
  [/\\[AZzhHRX]/, 'non-portable escape'],
  [/[^\x20-\x7e]/, 'non-ASCII character (write \\uXXXX)'],
];

function validate(c) {
  const kinds = new Set(c.kinds);
  for (const k of ['error_dialog', 'stack_trace', 'build_failed', 'run_failed']) {
    if (!kinds.has(k)) fail(`missing kind ${k}`);
  }
  for (const k of c.kinds) if (typeof c.copy.byKind[k] !== 'string') fail(`no copy for kind ${k}`);
  const ids = new Set();
  for (const r of c.rules) {
    if (ids.has(r.id)) fail(`duplicate rule id ${r.id}`);
    ids.add(r.id);
    if (!kinds.has(r.kind)) fail(`rule ${r.id}: unknown kind ${r.kind}`);
    if (r.kind === 'run_failed') fail(`rule ${r.id}: run_failed comes from events, not text rules`);
    if (!['any', 'dialog'].includes(r.scope)) fail(`rule ${r.id}: scope must be any|dialog`);
    if (!/^[im]*$/.test(r.flags) || new Set(r.flags).size !== r.flags.length) fail(`rule ${r.id}: flags must be a subset of "im"`);
    for (const [re, what] of NON_PORTABLE) if (re.test(r.pattern)) fail(`rule ${r.id}: ${what} is not portable`);
    try { new RegExp(r.pattern, r.flags); } catch (e) { fail(`rule ${r.id}: ${e.message}`); }
  }
  const keys = c.settings.keys;
  for (const [name, key] of Object.entries(keys)) {
    if (!(key in c.settings.defaults)) fail(`setting ${key} has no default`);
    if (key !== `petOffers.${name}`) fail(`setting key ${key} should be petOffers.${name}`);
  }
  for (const key of Object.keys(c.settings.defaults)) {
    if (!Object.values(keys).includes(key)) fail(`default ${key} has no key entry`);
  }
  if (typeof c.settings.defaults['petOffers.readOtherApps'] !== 'boolean') fail('petOffers.readOtherApps default must be a boolean');
  if (c.fixtures.length < 20) fail(`need at least 20 fixtures, have ${c.fixtures.length}`);
  const names = new Set();
  for (const f of c.fixtures) {
    if (names.has(f.name)) fail(`duplicate fixture name ${f.name}`);
    names.add(f.name);
    if (f.expected !== null && !kinds.has(f.expected)) fail(`fixture ${f.name}: unknown kind ${f.expected}`);
    if (f.rule !== undefined && !ids.has(f.rule)) fail(`fixture ${f.name}: unknown rule ${f.rule}`);
  }
}

validate(contract);

// ---------------------------------------------------------------- reference matcher (JS)

/** The matcher steps from contract.matcher, in JS. Each surface ports this. */
export function matchPetOffer(text, { dialog = false } = {}, c = contract) {
  let t = String(text).replace(/\r\n?/g, '\n');
  const max = c.settings.defaults['petOffers.maxTextChars'];
  if (t.length > max) t = t.slice(t.length - max);
  for (const rule of c.rules) {
    if (rule.scope === 'dialog' && !dialog) continue;
    const m = new RegExp(rule.pattern, rule.flags).exec(t);
    if (!m) continue;
    const start = t.lastIndexOf('\n', m.index - 1) + 1;
    let end = t.indexOf('\n', m.index);
    if (end < 0) end = t.length;
    const line = t.slice(start, end).trim().slice(0, c.limits.lineMaxChars);
    return { kind: rule.kind, ruleId: rule.id, line };
  }
  return null;
}

if (args.has('--test')) {
  let bad = 0;
  for (const f of contract.fixtures) {
    const got = matchPetOffer(f.text, { dialog: !!f.dialog });
    const gotKind = got ? got.kind : null;
    const ok = gotKind === f.expected && (f.rule === undefined || (got && got.ruleId === f.rule));
    if (!ok) {
      bad++;
      console.error(`FAIL ${f.name}: expected ${f.expected}${f.rule ? ` (${f.rule})` : ''}, got ${gotKind}${got ? ` (${got.ruleId}: "${got.line}")` : ''}`);
    }
  }
  // A dialog-only rule must never fire without the dialog role.
  const dialogOnly = contract.fixtures.filter((f) => f.rule && contract.rules.find((r) => r.id === f.rule).scope === 'dialog');
  for (const f of dialogOnly) {
    const got = matchPetOffer(f.text, { dialog: false });
    if (got && got.ruleId === f.rule) { bad++; console.error(`FAIL ${f.name}: dialog-only rule fired outside a dialog`); }
  }
  const total = contract.fixtures.length;
  if (bad) { console.error(`pet-offers fixtures: ${bad} failed of ${total}`); process.exit(1); }
  console.log(`pet-offers fixtures: ${total} passed (${contract.rules.length} rules)`);
  process.exit(0);
}

