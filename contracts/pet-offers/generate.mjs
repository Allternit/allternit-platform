    out.push(`        PetOfferRule(id: ${s(r.id)}, kind: ${kcase(r.kind)}, scope: .${r.scope === "any" ? "anyText" : r.scope}, pattern: ${s(r.pattern)}, caseInsensitive: ${r.flags.includes('i')}, multiline: ${r.flags.includes('m')}),`);
