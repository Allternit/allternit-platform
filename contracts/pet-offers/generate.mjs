// ---------------------------------------------------------------- Swift / Kotlin string literals

function lit(s, lang) {
  let o = '"';
  for (const ch of s) {
    const cp = ch.codePointAt(0);
    if (ch === '\\') o += '\\\\';
    else if (ch === '"') o += '\\"';
    else if (ch === '\n') o += '\\n';
    else if (ch === '\r') o += '\\r';
    else if (ch === '\t') o += '\\t';
    else if (ch === '$' && lang === 'kotlin') o += '\\$';
    else if (cp < 0x20 || cp > 0x7e) {
      if (lang === 'swift') o += `\\u{${cp.toString(16)}}`;
      // Kotlin: one \uXXXX per UTF-16 code unit (surrogate pairs for astral chars).
      else o += ch.split('').map((u) => `\\u${u.charCodeAt(0).toString(16).padStart(4, '0')}`).join('');
    } else o += ch;
  }
  return o + '"';
}

