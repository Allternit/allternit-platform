  out.push('enum PetOfferContract {');
  out.push(`    static let version = ${contract.version}`);
  out.push(`    static let surfaces: [String] = ${arr(contract.offer.fields.surface.enum, '    ')}`, '');
  out.push('    // MARK: Copy');
  out.push('    static let copyByKind: [PetOfferKind: String] = [');
  for (const k of contract.kinds) out.push(`        ${kcase(k)}: ${s(contract.copy.byKind[k])},`);
  out.push('    ]');
  out.push(`    static let fixItLabel = ${s(contract.copy.actions.fixIt)}`);
  out.push(`    static let muteLabel = ${s(contract.copy.actions.mute)}`);
