#!/usr/bin/env node
// Generates per-surface constants from the agent-modes contract
// (agent-modes-v1.json). Node 20, no dependencies.
//
//   node contracts/agent-modes/generate.mjs           # write outputs
//   node contracts/agent-modes/generate.mjs --check   # exit 1 if any output is stale
//
// Outputs (never edit them by hand):
//   cmd/gizzi-code/src/runtime/agent-modes/agentModes.gen.ts
//   surfaces/allternit-mobile/ios/Core/AgentModes/AgentModes.gen.swift
//   surfaces/allternit-mobile/android/core/api/src/main/java/com/allternit/core/api/gen/AgentModes.gen.kt
//
// allternit-ai keeps a byte copy of the JSON at src/lib/agent-modes/agent-modes-v1.json
// (its own repo, so it is not written from here). Keep the two identical.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const args = new Set(process.argv.slice(2));
const c = JSON.parse(fs.readFileSync(path.join(here, 'agent-modes-v1.json'), 'utf8'));
const HEADER = [
  'GENERATED by contracts/agent-modes/generate.mjs from contracts/agent-modes/agent-modes-v1.json.',
  'Do not edit. Change the JSON and run: node contracts/agent-modes/generate.mjs',
];

function fail(msg) { console.error(`agent-modes contract: ${msg}`); process.exit(1); }

const ORDER = ['agent', 'swarms', 'docs', 'sheets', 'slides', 'pdf', 'page', 'dashboard', 'ops', 'design', 'image', 'video', 'motion', 'app', 'build', 'research'];
const BETA = ['dashboard', 'ops', 'design', 'motion'];
const CAN = ['connectors', 'storage', 'ai'];
function validate() {
  const ids = c.modes.map((m) => m.id);
  if (ids.join() !== ORDER.join()) fail(`modes must be, in order: ${ORDER.join(', ')}`);
  const surfaces = new Set(c.surfaces);
  for (const m of c.modes) {
    for (const f of ['label', 'icon', 'placeholder']) if (typeof m[f] !== 'string' || !m[f]) fail(`${m.id}: missing ${f}`);
    if (/[^\x20-\x7e]/.test(m.label + m.placeholder)) fail(`${m.id}: label and placeholder are ASCII`);
    if ((m.beta) !== BETA.includes(m.id)) fail(`${m.id}: beta flag`);
    if (m.new !== (m.id === 'app')) fail(`${m.id}: new flag`);
    if (m.artifact !== !['agent', 'swarms'].includes(m.id)) fail(`${m.id}: artifact flag`);
    const t = m.launch && m.launch.type;
    if (!['agentMode', 'session', 'pick'].includes(t)) fail(`${m.id}: launch.type`);
    if (t === 'session' && !m.launch.session) fail(`${m.id}: session launch needs session`);
    if (t === 'pick' && !m.launch.pick) fail(`${m.id}: pick launch needs pick`);
    if (!Array.isArray(m.surfaces) || !m.surfaces.length || m.surfaces.some((s) => !surfaces.has(s))) fail(`${m.id}: surfaces`);
    for (const k of Object.keys(m.can)) {
      if (!CAN.includes(k)) fail(`${m.id}: unknown can.${k}`);
      if (typeof m.can[k].default !== 'boolean') fail(`${m.id}: can.${k}.default`);
    }
    if (!m.artifact && Object.keys(m.can).length) fail(`${m.id}: working styles have no "It can" row`);
  }
  for (const [from, to] of Object.entries(c.legacyIds)) if (!ids.includes(to)) fail(`legacy id ${from} -> unknown ${to}`);
  for (const to of Object.values(c.legacySurfaces)) if (!surfaces.has(to)) fail(`legacy surface -> unknown ${to}`);
}
validate();

const pascal = (s) => s.replace(/(^|[-_ ])(\w)/g, (_, __, ch) => ch.toUpperCase());
const camel = (s) => { const p = pascal(s); return p[0].toLowerCase() + p.slice(1); };
const snake = (s) => s.replace(/([a-z])([A-Z])/g, '$1_$2').replace(/-/g, '_').toUpperCase();
const jsonLit = (v) => JSON.stringify(v);
const kt = (v) => JSON.stringify(v).replace(/\$/g, '\\$');
const sw = (v) => JSON.stringify(v);
const nul = (v, f, none = 'null') => (v === null || v === undefined ? none : f(v));
const canOf = (m, k) => (m.can[k] ? (m.can[k].default ? 'on' : 'off') : 'none');

function ts() {
  const o = [...HEADER.map((l) => `// ${l}`), ''];
  o.push(`export const AGENT_MODES_VERSION = ${c.version} as const`, '');
  o.push(`export const AGENT_MODE_SURFACES = ${jsonLit(c.surfaces)} as const`);
  o.push('export type AgentModeSurfaceId = (typeof AGENT_MODE_SURFACES)[number]', '');
  o.push(`export const AGENT_MODE_IDS = ${jsonLit(c.modes.map((m) => m.id))} as const`);
  o.push('export type AgentModeId = (typeof AGENT_MODE_IDS)[number]', '');
  o.push('export type AgentModeLaunch =', '  | { type: "agentMode"; agentMode: string | null }', '  | { type: "session"; session: string; agentMode: string | null }', '  | { type: "pick"; pick: string }', '');
  o.push('export interface AgentModeCan { connectors?: { default: boolean }; storage?: { default: boolean }; ai?: { default: boolean } }', '');
  o.push('export interface AgentModeEntry {', '  id: AgentModeId', '  label: string', '  icon: string', '  artifact: boolean', '  beta: boolean', '  new: boolean', '  placeholder: string', '  launch: AgentModeLaunch', '  libraryKind: string | null', '  surfaces: readonly AgentModeSurfaceId[]', '  can: AgentModeCan', '}', '');
  o.push('export const AGENT_MODES: readonly AgentModeEntry[] = [');
  for (const m of c.modes) o.push(`  ${jsonLit(m)},`);
  o.push(']', '');
  o.push(`export const AGENT_MODE_LEGACY_IDS: Record<string, AgentModeId> = ${jsonLit(c.legacyIds)}`);
  o.push(`export const AGENT_MODE_LEGACY_SURFACES: Record<string, AgentModeSurfaceId> = ${jsonLit(c.legacySurfaces)}`, '');
  o.push('export function agentModeById(id: string): AgentModeEntry | undefined {', '  const key = AGENT_MODE_LEGACY_IDS[id] ?? id', '  return AGENT_MODES.find((m) => m.id === key)', '}', '');
  o.push('export function agentModesFor(surface: string): AgentModeEntry[] {', '  const s = AGENT_MODE_LEGACY_SURFACES[surface] ?? surface', '  return AGENT_MODES.filter((m) => (m.surfaces as readonly string[]).includes(s))', '}', '');
  return o.join('\n');
}

function swift() {
  const o = [...HEADER.map((l) => `// ${l}`), '// swiftlint:disable all', ''];
  o.push('enum AgentModeLaunchType: String, Sendable {', '    case agentMode', '    case session', '    case pick', '}', '');
  o.push('/// Default of one "It can" toggle: `.none` = the kind cannot honour it, so the row hides it.');
  o.push('enum AgentModeCanDefault: String, Sendable {', '    case none', '    case off', '    case on', '}', '');
  o.push('struct AgentModeEntry: Sendable {', '    let id: String', '    let label: String', '    let icon: String', '    let artifact: Bool', '    let beta: Bool', '    let isNew: Bool', '    let placeholder: String', '    let launchType: AgentModeLaunchType', '    /// Existing wire id (`website`, `data`, ...), nil when the kind has no agent mode.', '    let agentMode: String?', '    /// Session kind for `.session` launches.', '    let session: String?', '    let pick: String?', '    let libraryKind: String?', '    let surfaces: [String]', '    let connectors: AgentModeCanDefault', '    let storage: AgentModeCanDefault', '    let ai: AgentModeCanDefault', '}', '');
  o.push('enum AgentModes {');
  o.push(`    static let version = ${c.version}`);
  o.push(`    static let surfaces: [String] = ${sw(c.surfaces)}`);
  o.push(`    static let legacyIds: [String: String] = ${Object.keys(c.legacyIds).length ? sw(c.legacyIds) : '[:]'}`);
  o.push(`    static let legacySurfaces: [String: String] = ${Object.keys(c.legacySurfaces).length ? sw(c.legacySurfaces) : '[:]'}`, '');
  o.push('    static let all: [AgentModeEntry] = [');
  for (const m of c.modes) {
    const l = m.launch;
    o.push(`        AgentModeEntry(id: ${sw(m.id)}, label: ${sw(m.label)}, icon: ${sw(m.icon)}, artifact: ${m.artifact}, beta: ${m.beta}, isNew: ${m.new}, placeholder: ${sw(m.placeholder)}, launchType: .${l.type}, agentMode: ${nul(l.agentMode, sw, 'nil')}, session: ${nul(l.session, sw, 'nil')}, pick: ${nul(l.pick, sw, 'nil')}, libraryKind: ${nul(m.libraryKind, sw, 'nil')}, surfaces: ${sw(m.surfaces)}, connectors: .${canOf(m, 'connectors')}, storage: .${canOf(m, 'storage')}, ai: .${canOf(m, 'ai')}),`);
  }
  o.push('    ]', '');
  o.push('    static func mode(id: String) -> AgentModeEntry? {', '        let key = legacyIds[id] ?? id', '        return all.first { $0.id == key }', '    }', '');
  o.push('    static func modes(for surface: String) -> [AgentModeEntry] {', '        let s = legacySurfaces[surface] ?? surface', '        return all.filter { $0.surfaces.contains(s) }', '    }', '}', '');
  return o.join('\n');
}

function kotlin() {
  const o = [...HEADER.map((l) => `// ${l}`), '@file:Suppress("ktlint", "MaxLineLength")', '', 'package com.allternit.core.api.gen', ''];
  o.push('enum class AgentModeLaunchType { AGENT_MODE, SESSION, PICK }', '');
  o.push('/** Default of one "It can" toggle: NONE = the kind cannot honour it, so the row hides it. */');
  o.push('enum class AgentModeCanDefault { NONE, OFF, ON }', '');
  o.push('data class AgentModeEntry(', '    val id: String,', '    val label: String,', '    val icon: String,', '    val artifact: Boolean,', '    val beta: Boolean,', '    val isNew: Boolean,', '    val placeholder: String,', '    val launchType: AgentModeLaunchType,', '    /** Existing wire id (`website`, `data`, ...), null when the kind has no agent mode. */', '    val agentMode: String?,', '    val session: String?,', '    val pick: String?,', '    val libraryKind: String?,', '    val surfaces: List<String>,', '    val connectors: AgentModeCanDefault,', '    val storage: AgentModeCanDefault,', '    val ai: AgentModeCanDefault,', ')', '');
  const list = (a) => `listOf(${a.map(kt).join(', ')})`;
  const map = (m) => (Object.keys(m).length ? `mapOf(${Object.entries(m).map(([k, v]) => `${kt(k)} to ${kt(v)}`).join(', ')})` : 'emptyMap()');
  o.push('object AgentModes {', `    const val VERSION = ${c.version}`, `    val surfaces: List<String> = ${list(c.surfaces)}`, `    val legacyIds: Map<String, String> = ${map(c.legacyIds)}`, `    val legacySurfaces: Map<String, String> = ${map(c.legacySurfaces)}`, '');
  o.push('    val all: List<AgentModeEntry> = listOf(');
  for (const m of c.modes) {
    const l = m.launch;
    o.push(`        AgentModeEntry(${kt(m.id)}, ${kt(m.label)}, ${kt(m.icon)}, ${m.artifact}, ${m.beta}, ${m.new}, ${kt(m.placeholder)}, AgentModeLaunchType.${snake(l.type)}, ${nul(l.agentMode, kt)}, ${nul(l.session, kt)}, ${nul(l.pick, kt)}, ${nul(m.libraryKind, kt)}, ${list(m.surfaces)}, AgentModeCanDefault.${canOf(m, 'connectors').toUpperCase()}, AgentModeCanDefault.${canOf(m, 'storage').toUpperCase()}, AgentModeCanDefault.${canOf(m, 'ai').toUpperCase()}),`);
  }
  o.push('    )', '');
  o.push('    fun mode(id: String): AgentModeEntry? {', '        val key = legacyIds[id] ?: id', '        return all.firstOrNull { it.id == key }', '    }', '');
  o.push('    fun modes(surface: String): List<AgentModeEntry> {', '        val s = legacySurfaces[surface] ?: surface', '        return all.filter { s in it.surfaces }', '    }', '}', '');
  return o.join('\n');
}

const outputs = [
  ['cmd/gizzi-code/src/runtime/agent-modes/agentModes.gen.ts', ts()],
  ['surfaces/allternit-mobile/ios/Core/AgentModes/AgentModes.gen.swift', swift()],
  ['surfaces/allternit-mobile/android/core/api/src/main/java/com/allternit/core/api/gen/AgentModes.gen.kt', kotlin()],
];

let stale = 0;
for (const [rel, content] of outputs) {
  const p = path.join(repo, rel);
  if (args.has('--check')) {
    const cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    if (cur !== content) { stale++; console.error(`stale: ${rel}`); }
  } else {
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, content);
    console.log(`wrote ${rel}`);
  }
}
if (args.has('--check')) {
  if (stale) { console.error(`agent-modes: ${stale} generated file(s) stale; run node contracts/agent-modes/generate.mjs`); process.exit(1); }
  console.log('agent-modes generated files are up to date');
}
