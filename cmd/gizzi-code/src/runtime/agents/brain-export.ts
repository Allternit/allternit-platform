/**
 * Cross-brain export of the subagent catalog, so delegated work runs on cheap
 * models whichever CLI brain the session uses.
 *
 *   Claude Code: `--agents '<json>'` on every claude-cli launch
 *     (runtime/drivers/local-cli-driver.ts). Class → haiku / sonnet / opus.
 *   Codex: `~/.codex/agents/allternit-<slug>.toml`, written (only when
 *     changed) whenever a codex-cli app-server is launched. A model is set
 *     only for the small class and only when GIZZI_CODEX_SMALL_MODEL names
 *     one; otherwise Codex uses the session's model.
 *
 * Built-ins come from builtin-catalog.ts with the account's overrides applied;
 * custom types come from the last catalog sync.
 */
import fs from "fs/promises"
import os from "os"
import path from "path"
import { BUILTIN_CATALOG, type ModelClass } from "./builtin-catalog"
import { CatalogSync } from "./catalog-sync"

export interface ExportedAgent {
  slug: string
  description: string
  prompt: string
  tools?: string[]
  modelClass: ModelClass
}

export function exportedAgents(): ExportedAgent[] {
  const builtins = BUILTIN_CATALOG.map((a): ExportedAgent => {
    const o = CatalogSync.override(a.name)
    return {
      slug: a.name,
      description: o?.description ?? a.description,
      prompt: a.prompt,
      tools: a.tools,
      modelClass: o?.modelClass ?? a.modelClass,
    }
  })
  const taken = new Set(builtins.map((a) => a.slug))
  const customs = CatalogSync.customTypes()
    .filter((c) => !taken.has(c.slug))
    .map((c): ExportedAgent => ({
      slug: c.slug,
      description: c.description,
      prompt: c.prompt,
      tools: c.tools?.length ? c.tools : undefined,
      modelClass: c.modelClass,
    }))
  return [...builtins, ...customs]
}

/**
 * The user's own subagents from gizzi config (`agent.<name>` with
 * `mode: subagent` and a prompt), for a CLI brain's delegation tool. A
 * subagent denied edit gets Claude's read tools plus Bash.
 */
export async function configSubagents(): Promise<ExportedAgent[]> {
  const [{ Agent }, { PermissionNext }] = await Promise.all([
    import("@/runtime/loop/agent"),
    import("@/runtime/tools/guard/permission/next"),
  ])
  const catalog = new Set(BUILTIN_CATALOG.map((a) => a.name))
  return (await Agent.list())
    .filter((a) => a.mode === "subagent" && !a.native && !a.hidden && a.prompt?.trim() && !catalog.has(a.name))
    .map((a) => ({
      slug: a.name,
      description: a.description ?? a.name,
      prompt: a.prompt!,
      tools: PermissionNext.evaluate("edit", "*", a.permission).action === "deny" ? ["Read", "Grep", "Glob", "Bash"] : undefined,
      modelClass: a.modelClass ?? "inherit",
    }))
}

const CLAUDE_MODEL: Record<ModelClass, string> = {
  small: "haiku",
  standard: "sonnet",
  deep: "opus",
  inherit: "inherit",
}

/** JSON for Claude Code's `--agents` flag. Extra agents never replace a catalog type. */
export function claudeAgentsJson(extra: ExportedAgent[] = []): string {
  const out: Record<string, { description: string; prompt: string; tools?: string[]; model: string }> = {}
  const agents = exportedAgents()
  const taken = new Set(agents.map((a) => a.slug))
  for (const a of [...agents, ...extra.filter((e) => !taken.has(e.slug))]) {
    out[a.slug] = {
      description: a.description,
      prompt: a.prompt,
      ...(a.tools ? { tools: a.tools } : {}),
      model: CLAUDE_MODEL[a.modelClass],
    }
  }
  return JSON.stringify(out)
}

/** `--agents` flags for a claude-cli launch; empty when disabled. */
export function claudeAgentsFlags(extra: ExportedAgent[] = []): string[] {
  if (["1", "true"].includes((process.env.GIZZI_NO_BRAIN_AGENTS ?? "").toLowerCase())) return []
  try {
    return ["--agents", claudeAgentsJson(extra)]
  } catch {
    return []
  }
}

function tomlString(value: string): string {
  // Multi-line literal strings can't hold ''' — fall back to a basic string then.
  if (!value.includes("'''")) return `'''\n${value}'''`
  return JSON.stringify(value)
}

export function codexAgentToml(a: ExportedAgent): string {
  const lines = [
    `# Generated by gizzi from the Allternit subagent catalog. Edits are overwritten.`,
    `name = ${JSON.stringify(`allternit-${a.slug}`)}`,
    `description = ${JSON.stringify(a.description)}`,
  ]
  const small = process.env.GIZZI_CODEX_SMALL_MODEL?.trim()
  if (a.modelClass === "small" && small) lines.push(`model = ${JSON.stringify(small)}`)
  lines.push(`developer_instructions = ${tomlString(a.prompt.trim() + "\n")}`)
  return lines.join("\n") + "\n"
}

export function codexAgentsDir(): string {
  const home = process.env.CODEX_HOME?.trim() || path.join(process.env.GIZZI_TEST_HOME || os.homedir(), ".codex")
  return path.join(home, "agents")
}

let codexExport: Promise<void> | undefined

/** Write (only when changed) and prune `~/.codex/agents/allternit-*.toml`. Never throws. */
export function exportCodexAgents(): Promise<void> {
  if (["1", "true"].includes((process.env.GIZZI_NO_BRAIN_AGENTS ?? "").toLowerCase())) return Promise.resolve()
  if (codexExport) return codexExport
  codexExport = (async () => {
    try {
      const dir = codexAgentsDir()
      await fs.mkdir(dir, { recursive: true })
      const keep = new Set<string>()
      for (const a of exportedAgents()) {
        const file = path.join(dir, `allternit-${a.slug}.toml`)
        keep.add(file)
        const body = codexAgentToml(a)
        const current = await fs.readFile(file, "utf8").catch(() => undefined)
        if (current !== body) await fs.writeFile(file, body, "utf8")
      }
      for (const entry of await fs.readdir(dir).catch(() => [] as string[])) {
        if (!entry.startsWith("allternit-") || !entry.endsWith(".toml")) continue
        const file = path.join(dir, entry)
        if (!keep.has(file)) await fs.rm(file, { force: true })
      }
    } catch {
      // Export is an optimization; a failure must never block a launch.
    } finally {
      codexExport = undefined
    }
  })()
  return codexExport
}
