#!/usr/bin/env bun
/**
 * Writes the picker snapshot Gizzi ships with:
 *   src/runtime/providers/discovery/catalog.snapshot.gen.json
 * from the one hand-edited source (the same file allternit-api embeds,
 * cmd/allternit-api/src/cli_catalog.rs):
 *   src/runtime/providers/discovery/cli-catalog.json
 *
 * The snapshot is the offline fallback. At run time Gizzi overlays the live
 * GET /api/v1/picker-catalog on it (runtime-registry.ts `loadRuntimeSnapshot`),
 * so a catalog fix reaches installed Gizzi with a server deploy.
 *
 * Shape: the picker-catalog envelope (`schema`, `generatedAt`, `runtimes`)
 * plus `tools` (the CLI rows the runtimes point at) and `source` (path +
 * sha256 of cli-catalog.json). The file is rewritten only when its content
 * changes, so `generatedAt` stays put and a build does not dirty git.
 *
 * Run: bun script/gen-picker-snapshot.ts           (write if stale)
 *      bun script/gen-picker-snapshot.ts --check   (exit 1 if stale; not a build)
 */
import { createHash } from "node:crypto"
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

export const SNAPSHOT_SCHEMA = 1
const SOURCE_REL = "src/runtime/providers/discovery/cli-catalog.json"
const OUT_REL = "src/runtime/providers/discovery/catalog.snapshot.gen.json"

const pkgRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const sourcePath = path.join(pkgRoot, SOURCE_REL)
const outPath = path.join(pkgRoot, OUT_REL)

interface Snapshot {
  _generated: string
  schema: number
  generatedAt: string
  source: { path: string; sha256: string; catalogVersion: number }
  runtimes: unknown[]
  tools: unknown[]
}

function build(generatedAt: string): Snapshot {
  const raw = readFileSync(sourcePath)
  const catalog = JSON.parse(raw.toString("utf8")) as { version: number; runtimes?: unknown[]; tools?: unknown[] }
  return {
    _generated: `Generated by script/gen-picker-snapshot.ts from ${SOURCE_REL}. Do not edit; edit the source and rerun.`,
    schema: SNAPSHOT_SCHEMA,
    generatedAt,
    source: {
      path: SOURCE_REL,
      sha256: createHash("sha256").update(raw).digest("hex"),
      catalogVersion: catalog.version,
    },
    runtimes: catalog.runtimes ?? [],
    tools: catalog.tools ?? [],
  }
}

/** Serialized snapshot without `generatedAt`, for comparing content. */
function body(s: Snapshot): string {
  const { generatedAt: _ignored, ...rest } = s
  return JSON.stringify(rest)
}

function readExisting(): Snapshot | undefined {
  if (!existsSync(outPath)) return undefined
  try {
    return JSON.parse(readFileSync(outPath, "utf8")) as Snapshot
  } catch {
    return undefined
  }
}

const check = process.argv.includes("--check")
const existing = readExisting()
const fresh = build(existing?.generatedAt ?? new Date().toISOString())
const stale = !existing || body(existing) !== body(fresh)

if (check) {
  if (stale) {
    const why = !existing
      ? `${OUT_REL} is missing`
      : existing.source?.sha256 !== fresh.source.sha256
        ? `source sha256 ${fresh.source.sha256.slice(0, 12)} != snapshot ${String(existing.source?.sha256).slice(0, 12)}`
        : "snapshot content differs from the source"
    console.error(`gen-picker-snapshot: stale (${why}). Run: bun script/gen-picker-snapshot.ts`)
    process.exit(1)
  }
  console.log(`gen-picker-snapshot: ok (${fresh.runtimes.length} runtimes, ${fresh.tools.length} tools, sha256 ${fresh.source.sha256.slice(0, 12)})`)
  process.exit(0)
}

if (!stale) {
  console.log(`gen-picker-snapshot: up to date (${OUT_REL})`)
} else {
  const out = { ...fresh, generatedAt: new Date().toISOString() }
  writeFileSync(outPath, JSON.stringify(out, null, 2) + "\n")
  console.log(`gen-picker-snapshot: wrote ${OUT_REL} (${out.runtimes.length} runtimes, ${out.tools.length} tools)`)
}
