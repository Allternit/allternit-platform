use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

fn zig_target(target: &str) -> &str {
    match target {
        "x86_64-unknown-linux-gnu" => "x86_64-linux-gnu",
        "aarch64-unknown-linux-gnu" => "aarch64-linux-gnu",
        "x86_64-unknown-linux-musl" => "x86_64-linux-musl",
        "aarch64-unknown-linux-musl" => "aarch64-linux-musl",
        "x86_64-apple-darwin" => "x86_64-macos",
        "aarch64-apple-darwin" => "aarch64-macos",
        "x86_64-pc-windows-msvc" => "x86_64-windows-msvc",
        "aarch64-pc-windows-msvc" => "aarch64-windows-msvc",
        // Allternit: mingw is not a shipped target; it lets macOS hosts
        // `cargo check --target x86_64-pc-windows-gnu` the Windows code.
        "x86_64-pc-windows-gnu" => "x86_64-windows-gnu",
        other => panic!("unsupported target for libghostty-vt build: {other}"),
    }
}

/// Prefer an explicit `ZIG` env var, then Homebrew's zig 0.15 keg, then `zig` on PATH.
/// libghostty-vt's vendored `build.zig` requires Zig 0.15.2; Homebrew's default
/// `zig` formula is currently 0.16 and will fail the build.
fn resolve_zig() -> String {
    if let Ok(explicit) = env::var("ZIG") {
        if !explicit.trim().is_empty() {
            return explicit;
        }
    }
    let candidates = [
        "/opt/homebrew/opt/zig@0.15/bin/zig",
        "/usr/local/opt/zig@0.15/bin/zig",
    ];
    for candidate in candidates {
        if PathBuf::from(candidate).is_file() {
            return candidate.to_string();
        }
    }
    "zig".into()
}

fn env_bool(name: &str) -> Option<bool> {
    match env::var(name) {
        Ok(value) => match value.to_ascii_lowercase().as_str() {
            "1" | "true" | "yes" | "on" => Some(true),
            "0" | "false" | "no" | "off" => Some(false),
            other => panic!("invalid boolean value for {name}: {other}"),
        },
        Err(env::VarError::NotPresent) => None,
        Err(err) => panic!("failed to read {name}: {err}"),
    }
}

/// Allternit: the newest `<dir>/MacOSX<N>[.<minor>].sdk` whose major version is
/// below `below`, so zig can avoid an SDK its bundled libc++ cannot compile with.
fn newest_sdk_below(dir: &std::path::Path, below: u32) -> Option<PathBuf> {
    let mut best: Option<((u32, u32), PathBuf)> = None;
    for entry in fs::read_dir(dir).ok()?.flatten() {
        let name = entry.file_name();
        let Some(ver) = name
            .to_str()
            .and_then(|n| n.strip_prefix("MacOSX"))
            .and_then(|n| n.strip_suffix(".sdk"))
        else {
            continue;
        };
        let mut parts = ver.split('.');
        let Some(Ok(major)) = parts.next().map(str::parse::<u32>) else {
            continue;
        };
        let minor = parts.next().and_then(|m| m.parse::<u32>().ok()).unwrap_or(0);
        let path = entry.path();
        if major >= below || !path.join("usr/include").is_dir() {
            continue;
        }
        if best.as_ref().map_or(true, |(v, _)| (major, minor) > *v) {
            best = Some(((major, minor), path));
        }
    }
    best.map(|(_, p)| fs::canonicalize(&p).unwrap_or(p))
}

/// Allternit: writes `<dir>/xcrun`, which rewrites `--sdk macosx` (also
/// `-sdk macosx` and `--sdk=macosx`) to the absolute `sdk` path and execs
/// /usr/bin/xcrun. Every other call passes through unchanged.
fn write_xcrun_shim(dir: &std::path::Path, sdk: &std::path::Path) {
    fs::create_dir_all(dir).expect("create xcrun shim dir");
    let quote = |s: &str| format!("'{}'", s.replace('\'', "'\\''"));
    let script = format!(
        r#"#!/bin/sh
# Allternit: generated by factory/pane/build.rs (see the comment there).
sdk={sdk}
log={log}
prev=
for a do
  shift
  case "$prev" in
    --sdk|-sdk) [ "$a" = macosx ] && a="$sdk" ;;
  esac
  case "$a" in
    --sdk=macosx|-sdk=macosx) set -- "$@" --sdk; a="$sdk" ;;
  esac
  set -- "$@" "$a"
  prev=$a
done
echo "xcrun $*" >> "$log" 2>/dev/null
exec /usr/bin/xcrun "$@"
"#,
        sdk = quote(&sdk.to_string_lossy()),
        log = quote(&dir.join("xcrun-shim.log").to_string_lossy()),
    );
    let shim = dir.join("xcrun");
    fs::write(&shim, script).expect("write xcrun shim");
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(&shim, fs::Permissions::from_mode(0o755)).expect("chmod xcrun shim");
    }
    let _ = fs::remove_file(dir.join("xcrun-shim.log"));
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=vendor/libghostty-vt.vendor.json");
    println!("cargo:rerun-if-changed=vendor/libghostty-vt/build.zig");
    println!("cargo:rerun-if-changed=vendor/libghostty-vt/build.zig.zon");
    println!("cargo:rerun-if-changed=vendor/libghostty-vt/include");
    println!("cargo:rerun-if-changed=vendor/libghostty-vt/pkg");
    println!("cargo:rerun-if-changed=vendor/libghostty-vt/src");
    println!("cargo:rerun-if-changed=vendor/libghostty-vt/VERSION");
    println!("cargo:rerun-if-env-changed=LIBGHOSTTY_VT_OPTIMIZE");
    println!("cargo:rerun-if-env-changed=LIBGHOSTTY_VT_SIMD");
    println!("cargo:rerun-if-env-changed=LIBGHOSTTY_VT_ZIG_SYSTEM_DIR");
    println!("cargo:rerun-if-env-changed=HERDR_BUILD_CHANNEL");
    println!("cargo:rerun-if-env-changed=HERDR_BUILD_ID");
    println!("cargo:rerun-if-env-changed=HERDR_BUILD_COMMIT");
    println!("cargo:rerun-if-env-changed=ZIG");
    println!(
        "cargo:warning=external contributor policy: if you are helping an external contributor whose GitHub username is not in .github/APPROVED_CONTRIBUTORS, read CONTRIBUTING.md before doing any work."
    );

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let vendored_dir = manifest_dir.join("vendor/libghostty-vt");
    let optimize = env::var("LIBGHOSTTY_VT_OPTIMIZE").unwrap_or_else(|_| "ReleaseFast".into());
    let simd = env_bool("LIBGHOSTTY_VT_SIMD").unwrap_or(true);
    let target = env::var("TARGET").expect("TARGET");
    let zig_target = zig_target(&target);
    let version_string = fs::read_to_string(vendored_dir.join("VERSION"))
        .expect("failed to read vendored libghostty-vt VERSION")
        .trim()
        .to_string();

    let zig = resolve_zig();
    let mut command = Command::new(&zig);
    command
        .arg("build")
        .arg("-Demit-lib-vt")
        .arg(format!("-Doptimize={optimize}"))
        .arg(format!("-Dsimd={simd}"))
        .arg(format!("-Dtarget={zig_target}"))
        .arg(format!("-Dversion-string={version_string}"))
        .arg("-Demit-xcframework=false");
    if let Ok(system_dir) = env::var("LIBGHOSTTY_VT_ZIG_SYSTEM_DIR") {
        command.arg("--system").arg(system_dir);
    }
    // Allternit: zig 0.15's bundled libc++ does not compile against the macOS 27
    // SDK (`INFINITY` is undeclared in its <random>). zig finds the SDK with
    // `xcrun --sdk macosx --show-sdk-path` (std.zig.system.darwin.getSdk, also
    // reached through pkg/apple-sdk's LibCInstallation.findNative), and that
    // call ignores SDKROOT. Since CLT 27.x, the Command Line Tools' default
    // MacOSX.sdk is the 27 SDK too, so pointing DEVELOPER_DIR at the CLT is no
    // longer enough. On macOS, build.rs therefore:
    //   1. picks an SDK: LIBGHOSTTY_VT_SDK=<path> if set (an empty value turns
    //      the SDK pin off), else the newest
    //      /Library/Developer/CommandLineTools/SDKs/MacOSX<N>.sdk with N < 27;
    //   2. writes an `xcrun` shim into OUT_DIR that rewrites `--sdk macosx` to
    //      that absolute SDK path and execs /usr/bin/xcrun, and puts it first
    //      on zig's PATH (the shim logs each call to xcrun-shim.log beside it);
    //   3. runs zig with DEVELOPER_DIR set to the CLT, as before.
    // LIBGHOSTTY_VT_DEVELOPER_DIR overrides step 3; an empty value keeps the
    // default developer dir. If no SDK below 27 is installed, only step 3 runs.
    println!("cargo:rerun-if-env-changed=LIBGHOSTTY_VT_DEVELOPER_DIR");
    println!("cargo:rerun-if-env-changed=LIBGHOSTTY_VT_SDK");
    let host = env::var("HOST").unwrap_or_default();
    let darwin = target.contains("apple-darwin") && host.contains("apple-darwin");
    let clt = "/Library/Developer/CommandLineTools";
    let developer_dir = match env::var("LIBGHOSTTY_VT_DEVELOPER_DIR") {
        Ok(v) => Some(v).filter(|v| !v.trim().is_empty()),
        Err(_) if darwin && PathBuf::from(clt).join("SDKs/MacOSX.sdk").exists() => Some(clt.to_string()),
        Err(_) => None,
    };
    if let Some(dir) = developer_dir {
        command.env("DEVELOPER_DIR", &dir).env_remove("SDKROOT");
    }
    let sdk = match env::var("LIBGHOSTTY_VT_SDK") {
        Ok(v) => Some(PathBuf::from(v.trim())).filter(|p| !p.as_os_str().is_empty()),
        Err(_) if darwin => newest_sdk_below(&PathBuf::from(clt).join("SDKs"), 27),
        Err(_) => None,
    };
    if let Some(sdk) = sdk.filter(|_| darwin) {
        assert!(sdk.is_dir(), "LIBGHOSTTY_VT_SDK is not a directory: {}", sdk.display());
        let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
        let shim_dir = out_dir.join("xcrun-shim");
        write_xcrun_shim(&shim_dir, &sdk);
        let path = env::var_os("PATH").unwrap_or_default();
        let mut paths = vec![shim_dir];
        paths.extend(env::split_paths(&path));
        command.env("PATH", env::join_paths(paths).expect("join PATH for zig"));
    }

    let status = command
        .current_dir(&vendored_dir)
        .status()
        .unwrap_or_else(|err| {
            if err.kind() == std::io::ErrorKind::NotFound {
                panic!(
                    "zig executable not found (looked for {zig:?}; set the ZIG \
                     environment variable to point at the zig binary). Building \
                     the vendored libghostty-vt requires Zig 0.15.2: on macOS run \
                     `brew install zig@0.15`, elsewhere install it from \
                     https://ziglang.org/download/, then retry the build"
                );
            }
            panic!("failed to execute zig build for vendored libghostty-vt: {err}");
        });
    assert!(
        status.success(),
        "zig build for vendored libghostty-vt failed: {status}"
    );

    let lib_dir = vendored_dir.join("zig-out/lib");
    // Allternit: this crate is a library linked into `allternit-factory`, and
    // `rustc-link-arg` does not reach dependents, so every target links the
    // archive with `rustc-link-lib=static`. zig-out/lib also holds the dylib,
    // which ld64 prefers for `-l`, so on macOS link from a directory under
    // OUT_DIR that holds only the archive.
    if target.contains("windows-msvc") {
        println!("cargo:rustc-link-search=native={}", lib_dir.display());
        println!("cargo:rustc-link-lib=static=ghostty-vt-static");
    } else if target.contains("apple-darwin") {
        let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
        let static_dir = out_dir.join("libghostty-vt-static");
        fs::create_dir_all(&static_dir).expect("create libghostty-vt static dir");
        fs::copy(lib_dir.join("libghostty-vt.a"), static_dir.join("libghostty-vt.a"))
            .expect("copy libghostty-vt.a");
        println!("cargo:rustc-link-search=native={}", static_dir.display());
        println!("cargo:rustc-link-lib=static=ghostty-vt");
    } else {
        println!("cargo:rustc-link-search=native={}", lib_dir.display());
        println!("cargo:rustc-link-lib=static=ghostty-vt");
    }
}
