#!/usr/bin/env node
/**
 * Writes cmd/allternit-api/assets/official-mcp-servers.json from allternit-ai's
 * generated src/views/mini-apps/official-servers.ts (itself generated from the W3
 * catalogue by allternit-ai scripts/gen-official-servers.mjs). One source: rerun
 * this after that file changes.
 *
 *   node scripts/gen-official-mcp-servers.mjs [path/to/official-servers.ts]
 *
 * Default path: ../allternit-ai/src/views/mini-apps/official-servers.ts next to
 * this repo. allternit-api reads the JSON to fall back to a vendor's official MCP
 * server when the catalog can't issue a sign-in (connector_routes.rs).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..");
const src = process.argv[2] ?? path.resolve(repo, "../allternit-ai/src/views/mini-apps/official-servers.ts");
const text = fs.readFileSync(src, "utf8");
const marker = "OFFICIAL_SERVERS: readonly OfficialServer[] = ";
const start = text.indexOf(marker);
if (start < 0) throw new Error(`${src}: OFFICIAL_SERVERS not found`);
const body = text.slice(start + marker.length).trim().replace(/;\s*$/, "");
const servers = JSON.parse(body).map(({ id, name, url, auth }) => ({ id, name, url, auth }));
for (const s of servers) {
  if (!/^https:\/\//.test(s.url)) throw new Error(`${s.id}: not an https URL`);
}
const out = path.join(repo, "cmd/allternit-api/assets/official-mcp-servers.json");
fs.writeFileSync(out, JSON.stringify({
  _source: "Generated by scripts/gen-official-mcp-servers.mjs from allternit-ai src/views/mini-apps/official-servers.ts. Do not edit by hand.",
  servers,
}, null, 2) + "\n");
console.log(`wrote ${servers.length} servers to ${path.relative(repo, out)}`);
