#!/usr/bin/env node
/**
 * Generate resources/company.json from environment variables.
 *
 * This is used when packaging the Allternit Platform app so that company
 * standards (auth, endpoints) are baked into every build and users do not have
 * to touch env vars on each host computer.
 *
 * Encryption is NOT baked here. The local encryption key is per-host: it is
 * generated once on first onboarding and stored in that machine's OS keychain
 * (service "allternit-platform", account "platform:encryption-key"). Baking a
 * shared key into the package would make it extractable and identical across
 * installs, which is not real encryption, so this file emits an empty key and
 * the Rust side resolves env -> company(empty) -> keychain.
 *
 * Required / commonly set env vars:
 *   ALLTERNIT_TENANT_ID              - tenant marker (default: allternit-default)
 *   ALLTERNIT_GATEWAY_URL            - API gateway URL (default: http://localhost:8013)
 *   ALLTERNIT_TERMINAL_SERVER_URL    - Gizzi runtime URL (default: http://127.0.0.1:4096)
 *   ALLTERNIT_FACTORY_API_URL        - Base URL of the in-process Factory API (default: http://127.0.0.1:8080)
 *   ALLTERNIT_FACTORY_WORKSPACE_ID   - Factory workspace ID (default: default)
 *   ALLTERNIT_CRON_DAEMON_URL        - Cron daemon URL (default: http://127.0.0.1:4096/cron)
 *   ALLTERNIT_VM_DIR                 - VM storage directory (optional)
 *   ALLTERNIT_SELF_HOSTED            - Self-hosted mode, skips Clerk (default: false)
 *   NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY - Clerk publishable key (optional)
 *   CLERK_JWKS_URL                   - Clerk JWKS URL (optional)
 *   CLERK_ISSUER                     - Clerk JWT issuer (optional)
 *   CLERK_WEBHOOK_SECRET             - Clerk webhook secret (optional)
 *
 * Usage:
 *   node scripts/generate-company-config.cjs
 *   node scripts/generate-company-config.cjs --out ./dist/company.json
 */

const fs = require('fs');
const path = require('path');

function getEnv(name, fallback = '') {
  const value = process.env[name];
  return value !== undefined && value.trim().length > 0 ? value.trim() : fallback;
}

function loadExistingConfig(outPath) {
  try {
    return JSON.parse(fs.readFileSync(outPath, 'utf8'));
  } catch {
    return null;
  }
}

function main() {
  const args = process.argv.slice(2);
  const outArg = args.find((a) => a.startsWith('--out='));
  const outPath = outArg
    ? path.resolve(outArg.split('=')[1])
    : path.resolve(__dirname, '..', 'resources', 'company.json');

  // Encryption key is intentionally NOT baked. Per-host key lives in the OS
  // keychain; see cmd/allternit-api/src/token_crypto.rs (ensure_platform_key).
  const encryptionKey = getEnv('ALLTERNIT_ENCRYPTION_KEY', '');

  const existing = loadExistingConfig(outPath) ?? {};

  const config = {
    $schema: 'https://allternit.io/schemas/company-config.json',
    _comment:
      'Company-level configuration baked into packaged Allternit Platform apps. Generated by scripts/generate-company-config.cjs. Encryption key is per-host keychain, not baked.',
    tenantId: getEnv('ALLTERNIT_TENANT_ID', existing.tenantId ?? 'allternit-default'),
    gatewayUrl: getEnv('ALLTERNIT_GATEWAY_URL', existing.gatewayUrl ?? 'http://localhost:8013'),
    terminalServerUrl: getEnv('ALLTERNIT_TERMINAL_SERVER_URL', existing.terminalServerUrl ?? 'http://127.0.0.1:4096'),
    // An existing company.json written before the Factory rename carries
    // railsUrl / railsWorkspaceId; carry their values over to the new keys.
    factoryApiUrl: getEnv('ALLTERNIT_FACTORY_API_URL', existing.factoryApiUrl ?? existing.railsUrl ?? 'http://127.0.0.1:8080'),
    factoryWorkspaceId: getEnv('ALLTERNIT_FACTORY_WORKSPACE_ID', existing.factoryWorkspaceId ?? existing.railsWorkspaceId ?? 'default'),
    cronDaemonUrl: getEnv('ALLTERNIT_CRON_DAEMON_URL', existing.cronDaemonUrl ?? 'http://127.0.0.1:4096/cron'),
    vmDir: getEnv('ALLTERNIT_VM_DIR', existing.vmDir ?? ''),
    clerkPublishableKey: getEnv('NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY', existing.clerkPublishableKey ?? ''),
    clerkProxyUrl: getEnv('NEXT_PUBLIC_CLERK_PROXY_URL', existing.clerkProxyUrl ?? ''),
    clerkJwksUrl: getEnv('CLERK_JWKS_URL', existing.clerkJwksUrl ?? ''),
    clerkIssuer: getEnv('CLERK_ISSUER', existing.clerkIssuer ?? ''),
    clerkWebhookSecret: getEnv('CLERK_WEBHOOK_SECRET', existing.clerkWebhookSecret ?? ''),
    selfHosted: getEnv('ALLTERNIT_SELF_HOSTED', existing.selfHosted ? 'true' : 'false').toLowerCase() === 'true',
    encryptionKey,
  };

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, JSON.stringify(config, null, 2) + '\n', 'utf8');

  console.log(`Wrote company config to ${outPath}`);
  if (process.env.ALLTERNIT_ENCRYPTION_KEY) {
    console.log('ALLTERNIT_ENCRYPTION_KEY is set; it overrides per-host keychain (dev/CI only).');
  }
  if (!config.clerkPublishableKey && !config.selfHosted) {
    console.log('No Clerk publishable key set and selfHosted is false. Set ALLTERNIT_SELF_HOSTED=true for packaged apps without Clerk.');
  }
  if (config.selfHosted) {
    console.log('Self-hosted mode enabled. Clerk JWT verification will be skipped.');
  }
}

main();
