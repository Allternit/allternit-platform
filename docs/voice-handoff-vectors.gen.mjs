#!/usr/bin/env node
// Generates docs/voice-handoff-vectors.json: the shared test vector for the
// voice key QR handoff (web/Desktop/PWA sender, iOS receiver). Node 20+, no
// dependencies. Deterministic: fixed private scalars, sid and nonce, so the
// output is byte-identical on every run.
//
//   node docs/voice-handoff-vectors.gen.mjs          # print the JSON
//   node docs/voice-handoff-vectors.gen.mjs --write  # rewrite the .json file
//   node docs/voice-handoff-vectors.gen.mjs --check  # fail if the .json differs
//
// Protocol (plan snoopy-napping-rabbit, design decision 1):
//   QR1  = allternit-voice:1:<sid>:<pubA b64url>          (sender shows)
//   receiver PUTs pubB to /api/v1/voice/handoff/:sid/receiver; sender GETs it
//   code = SHA-256(utf8(sid) || pubA_raw || pubB_raw), first 4 bytes as a
//          big-endian uint32, mod 1_000_000, zero-padded to 6 digits
//   key  = HKDF-SHA256(ikm = ECDH shared secret x-coordinate (32 bytes),
//                      salt = utf8(sid), info = "allternit-voice-key-handoff-v1", L = 32)
//   QR2  = allternit-voice:2:<sid>:<nonce b64url>:<ciphertext||tag b64url>
//          AES-256-GCM, 12-byte random nonce, no AAD, 16-byte tag appended
// pub*_raw are uncompressed SEC1 points (65 bytes, 0x04 || X || Y). All
// base64url is unpadded. The server never sees QR contents.

import { createECDH, createHash, createCipheriv, createDecipheriv, createPrivateKey, hkdfSync } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const b64url = (buf) => Buffer.from(buf).toString('base64url');
const INFO = 'allternit-voice-key-handoff-v1';

// Fixed inputs. Test keys only; never use them for anything real.
const senderScalarHex = 'c9afa9d845ba75166b5c215767b1d6934e50c3db36e89b127b8a622b120f6721';
const receiverScalarHex = '7d7dc5f71eb29ddaf80d6214632eeae03d9058af1fb6d22ed80badb62bc1a534';
const sid = b64url(Buffer.from('000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f', 'hex'));
const nonce = Buffer.from('a1a2a3a4a5a6a7a8a9aaabac', 'hex');
const payload = '{"provider":"elevenlabs","api_key":"sk_test_123","voice_id":"21m00Tcm4TlvDq8ikWAM"}';

function party(scalarHex) {
  const ecdh = createECDH('prime256v1');
  ecdh.setPrivateKey(Buffer.from(scalarHex, 'hex'));
  const pub = ecdh.getPublicKey(null, 'uncompressed');
  const jwk = {
    kty: 'EC',
    crv: 'P-256',
    d: b64url(Buffer.from(scalarHex, 'hex')),
    x: b64url(pub.subarray(1, 33)),
    y: b64url(pub.subarray(33, 65)),
  };
  const pkcs8 = createPrivateKey({ key: jwk, format: 'jwk' }).export({ format: 'der', type: 'pkcs8' });
  return { ecdh, pub, jwk, pkcs8 };
}

const A = party(senderScalarHex);
const B = party(receiverScalarHex);

const sharedA = A.ecdh.computeSecret(B.pub);
const sharedB = B.ecdh.computeSecret(A.pub);
if (!sharedA.equals(sharedB) || sharedA.length !== 32) throw new Error('ECDH mismatch');

const digest = createHash('sha256').update(Buffer.from(sid, 'utf8')).update(A.pub).update(B.pub).digest();
const confirmCode = String(digest.readUInt32BE(0) % 1_000_000).padStart(6, '0');

const aesKey = Buffer.from(hkdfSync('sha256', sharedA, Buffer.from(sid, 'utf8'), Buffer.from(INFO, 'utf8'), 32));

const cipher = createCipheriv('aes-256-gcm', aesKey, nonce);
const ct = Buffer.concat([cipher.update(payload, 'utf8'), cipher.final(), cipher.getAuthTag()]);

// Self-check: the receiver side decrypts; a wrong key fails.
const decipher = createDecipheriv('aes-256-gcm', aesKey, nonce);
decipher.setAuthTag(ct.subarray(ct.length - 16));
const back = Buffer.concat([decipher.update(ct.subarray(0, ct.length - 16)), decipher.final()]).toString('utf8');
if (back !== payload) throw new Error('roundtrip failed');

const vector = {
  description:
    'Shared test vector for the Allternit voice key QR handoff. Generated by docs/voice-handoff-vectors.gen.mjs; do not edit by hand. Test keys only.',
  version: 1,
  curve: 'P-256',
  encoding: 'base64url without padding; public keys are uncompressed SEC1 points (65 bytes, 0x04||X||Y)',
  sender: {
    private_scalar_hex: senderScalarHex,
    private_pkcs8_b64url: b64url(A.pkcs8),
    private_jwk: A.jwk,
    public_uncompressed_b64url: b64url(A.pub),
  },
  receiver: {
    private_scalar_hex: receiverScalarHex,
    private_pkcs8_b64url: b64url(B.pkcs8),
    private_jwk: B.jwk,
    public_uncompressed_b64url: b64url(B.pub),
  },
  sid,
  confirm_code: {
    rule: 'SHA-256(utf8(sid) || pubA_raw || pubB_raw); first 4 bytes as big-endian uint32; mod 1000000; zero-pad to 6 digits',
    sha256_hex: digest.toString('hex'),
    code: confirmCode,
  },
  ecdh_shared_x_hex: sharedA.toString('hex'),
  hkdf: {
    hash: 'SHA-256',
    salt_utf8: sid,
    info_utf8: INFO,
    length: 32,
    okm_hex: aesKey.toString('hex'),
  },
  aes_gcm: {
    nonce_hex: nonce.toString('hex'),
    nonce_b64url: b64url(nonce),
    aad: 'none',
    tag_bytes: 16,
    plaintext_utf8: payload,
    ciphertext_and_tag_b64url: b64url(ct),
  },
  qr1: `allternit-voice:1:${sid}:${b64url(A.pub)}`,
  qr2: `allternit-voice:2:${sid}:${b64url(nonce)}:${b64url(ct)}`,
};

const out = `${JSON.stringify(vector, null, 2)}\n`;
const target = fileURLToPath(new URL('./voice-handoff-vectors.json', import.meta.url));
if (process.argv.includes('--write')) {
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
} else if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== out) {
    console.error(`${target} is out of date; run with --write`);
    process.exit(1);
  }
  console.log('voice-handoff-vectors.json is current');
} else {
  process.stdout.write(out);
}
